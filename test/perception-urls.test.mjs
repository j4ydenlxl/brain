// test/perception-urls.test.mjs: the allow list is code (bench/perception-urls.mjs) and the fixture is its
// output, so the HIS DATA row counts the file as data the tree writes itself.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALLOW, FIXTURE_FILE, render, writeFixture, fixtureMatches, quotedFragments } from '../bench/perception-urls.mjs';
import { loadFixture } from '../bench/perception.mjs';
import { fixtureCoverage, GENERATED_RE, mentionsFile } from '../bench/gate.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

test('perception-urls: the writer renders the list, writes it, and reports a rewrite only when the bytes differ', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'perception-urls-'));
  const file = path.join(dir, 'perception-urls.json');
  const first = writeFixture(file);
  assert.equal(first.changed, true, 'an absent file is a change');
  assert.equal(first.bytes, Buffer.byteLength(render()));
  assert.equal(fs.readFileSync(file, 'utf8'), render());
  const second = writeFixture(file);
  assert.equal(second.changed, false, 'the same bytes are not a change');
  assert.equal(fixtureMatches(file), true);
  fs.writeFileSync(file, '{}\n');
  assert.equal(fixtureMatches(file), false, 'a file that differs does not match');
  fs.rmSync(dir, { recursive: true, force: true });
});

test('perception-urls: the list passes the perception bench\'s own loader and every expect is a title fragment, not the url', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'perception-urls-'));
  const file = path.join(dir, 'perception-urls.json');
  writeFixture(file);
  const f = loadFixture(file);
  assert.equal(f.urls.length, ALLOW.urls.length);
  assert.deepEqual(f.hosts, ALLOW.hosts);
  for (const u of ALLOW.urls) {
    assert.equal(new URL(u.url).hostname, u.host, 'host matches the url');
    assert.ok(ALLOW.hosts.includes(u.host), 'host is on the allow list');
    assert.equal(u.url.includes(u.expect), false, 'the expect is not part of the url');
  }
  assert.equal(quotedFragments().length, 2 * ALLOW.urls.length);
  fs.rmSync(dir, { recursive: true, force: true });
});

test('perception-urls: the fixture on disk is exactly what the writer renders, and the census counts it as written by the tree', (t) => {
  const sources = path.join(ROOT, 'bench', 'fixtures', 'SOURCES.md');
  if (!fs.existsSync(FIXTURE_FILE) || !fs.existsSync(sources)) { t.skip('bench/fixtures is never committed: this host has no fixture or no SOURCES.md'); return; }
  assert.equal(fixtureMatches(), true, 'run node bench/perception-urls.mjs: the fixture on disk differs from the writer');
  const lines = fs.readFileSync(sources, 'utf8').split(/\r?\n/).filter((l) => mentionsFile(l, 'perception-urls.json'));
  assert.equal(lines.length, 1, 'exactly one SOURCES.md line names the file');
  const m = lines[0].match(GENERATED_RE);
  assert.ok(m, 'the line carries a generated-by clause');
  assert.equal(m[1], 'bench/perception-urls.mjs');
  assert.ok(fs.existsSync(path.join(ROOT, m[1])), 'the writer exists in the tree');
  for (const s of quotedFragments()) assert.ok(lines[0].includes(s), 'the line names the quoted fragment ' + JSON.stringify(s));
  const entry = fixtureCoverage(path.join(ROOT, 'bench', 'fixtures')).list.find((x) => x.file === 'perception-urls.json');
  assert.ok(entry, 'the census sees the file');
  assert.equal(entry.covered, true, 'the row counts it as the tree\'s own data');
  assert.equal(entry.by.generated, true);
  assert.equal(entry.by.licence, 'generated by bench/perception-urls.mjs');
});
