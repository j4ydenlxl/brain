// test/his-data.test.mjs: the HIS DATA row on more than one kind of SOURCES.md line, and the one
// line board 23 item his-data wrote (bench/fixtures/SOURCES.md, perception-urls.json).
//
// Why this file exists: the first pass of the item put a Wikipedia fragment's licence token
// ("CC BY-SA 4.0") on the perception-urls.json line. The gate reads ANY licence token on a line
// that names a file as that file's licence, so the row printed GREEN and "bytes of his data 0"
// while the same line said the file was hand-authored in this repo. A snippet's licence is not
// the file's licence (REUSE 3.3 licenses a snippet with SPDX-SnippetBegin/End, the file keeps its
// own). These cases pin both halves: what the parser does with each kind of line, and what the
// real line may and may not say.
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { fixtureCoverage, hisDataRow, mentionsFile, LICENCE_RE, GENERATED_RE } = await import('../bench/gate.mjs');

function put(root, rel, text) {
  const p = path.join(root, ...rel.split('/'));
  mkdirSync(path.dirname(p), { recursive: true });
  writeFileSync(p, text);
  return Buffer.byteLength(text);
}

test('his-data: six kinds of line, each read the way the row needs', () => {
  const root = mkdtempSync(path.join(tmpdir(), 'his-data-test-'));
  try {
    assert.equal(existsSync(path.join(ROOT, 'bench', 'answer.mjs')), true, 'the generated case needs a writer that exists');
    assert.equal(existsSync(path.join(ROOT, 'bench', 'no-such-writer-his-data.mjs')), false, 'the ghost case needs a writer that does not');
    put(root, 'SOURCES.md', [
      '# sources',
      '- licensed.json: downloaded from example.org, CC0-1.0.',
      '- made.json: generated by node bench/answer.mjs from planted questions.',
      '- ghost.json: generated by node bench/no-such-writer-his-data.mjs.',
      '- authored.json: hand-authored in this repo, all rights reserved under its LICENSE; no open licence chosen.',
      '- quoted.json: hand-authored in this repo, quoting one fragment of a public page.',
      '  - that fragment is from a CC BY-SA 4.0 page',
      '- tokened.json: hand-authored in this repo; its one quoted fragment is CC BY-SA 4.0.',
    ].join('\n'));
    const b = {
      licensed: put(root, 'licensed.json', 'a'.repeat(11)),
      made: put(root, 'made.json', 'b'.repeat(13)),
      ghost: put(root, 'ghost.json', 'c'.repeat(17)),
      authored: put(root, 'authored.json', 'd'.repeat(19)),
      quoted: put(root, 'quoted.json', 'e'.repeat(23)),
      tokened: put(root, 'tokened.json', 'f'.repeat(29)),
    };
    const cov = fixtureCoverage(root);
    const by = Object.fromEntries(cov.list.map((x) => [x.file, x]));
    assert.equal(by['licensed.json'].by.licence, 'CC0-1.0', 'a licence on the file line covers it');
    assert.equal(by['made.json'].by.licence, 'generated by bench/answer.mjs', 'a writer of the tree covers it with no licence token');
    assert.equal(by['made.json'].by.generated, true);
    assert.equal(by['ghost.json'].covered, false, 'a writer that does not exist covers nothing');
    assert.equal(by['authored.json'].covered, false, 'hand-authored, all rights reserved: his bytes, not public ones');
    assert.equal(by['quoted.json'].covered, false, 'a fragment licence on a line that does not name the file covers nothing');
    // the mechanism behind the first pass: ANY token on the file line is read as the file licence
    assert.equal(by['tokened.json'].by.licence, 'CC BY-SA 4.0', 'a fragment licence on the file line is read as the whole file licence');
    assert.deepEqual(cov.notice.map((n) => n.file), ['SOURCES.md']);
    assert.equal(cov.files, 6);
    assert.equal(cov.covered, 3);
    assert.deepEqual(cov.uncovered.map((u) => u.file).sort(), ['authored.json', 'ghost.json', 'quoted.json']);
    assert.equal(cov.uncoveredBytes, b.ghost + b.authored + b.quoted);
    assert.equal(cov.coveredBytes, b.licensed + b.made + b.tokened);
    const row = hisDataRow(cov, 'fixtures');
    assert.equal(row.ok, false);
    assert.match(row.line, /^HIS DATA RED: 3 of 6 data files under fixtures/);
    assert.match(row.line, new RegExp('uncovered 3 files, ' + (b.ghost + b.authored + b.quoted) + ' bytes'));
    assert.match(row.line, /authored\.json 19/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test('his-data: the perception-urls.json line names every quoted fragment and is written by a tool of the tree', (t) => {
  const sources = path.join(ROOT, 'bench', 'fixtures', 'SOURCES.md');
  const fixture = path.join(ROOT, 'bench', 'fixtures', 'perception-urls.json');
  if (!existsSync(sources) || !existsSync(fixture)) { t.skip('bench/fixtures is never committed: this host has no SOURCES.md or no perception-urls.json'); return; }
  const lines = readFileSync(sources, 'utf8').split(/\r?\n/).filter((l) => mentionsFile(l, 'perception-urls.json'));
  assert.equal(lines.length, 1, 'exactly one line names the file');
  const line = lines[0];
  const f = JSON.parse(readFileSync(fixture, 'utf8'));
  const fragments = f.urls.flatMap((u) => [u.expect, u.fact]);
  assert.equal(fragments.length, 2 * f.urls.length);
  assert.ok(fragments.length > 0, 'a fixture with no quoted fragment would make this check true of nothing');
  for (const s of fragments) {
    assert.equal(typeof s, 'string');
    assert.ok(line.includes(s), 'the line names the quoted fragment ' + JSON.stringify(s));
  }
  // Since board 23 (2026-09-26) a tool of the tree writes the file: bench/perception-urls.mjs holds the
  // allow list as code and the fixture is its output, so the row counts it as the tree's own data.
  // No licence token is claimed for it: the fragments are quoted, the rest is code of the tree.
  assert.equal(line.match(LICENCE_RE), null, 'no licence token: a fragment licence is not the file licence');
  const gen = line.match(GENERATED_RE);
  assert.ok(gen, 'a generated-by clause names the writer');
  assert.equal(gen[1], 'bench/perception-urls.mjs');
  assert.ok(existsSync(path.join(ROOT, gen[1])), 'the writer exists in the tree');
  const entry = fixtureCoverage(path.join(ROOT, 'bench', 'fixtures')).list.find((x) => x.file === 'perception-urls.json');
  assert.ok(entry, 'the census sees the file');
  assert.equal(entry.covered, true, 'the row counts it as data the tree writes itself');
  assert.equal(entry.by.generated, true);
});

// The control for the GREEN above (board 23 his-data fix pass, 2026-09-27). The row counts
// perception-urls.json as the tree's own data on the strength of ONE clause (generated by node
// bench/perception-urls.mjs) and the writer existing. So the control is the real line with the clause
// taken away, and with the writer swapped for one that does not exist: each must turn the file
// uncovered, or the GREEN measured something other than the clause. A fourth arm pins what the census
// cannot see: it never compares bytes, so a drifted fixture stays covered; only the writer's own
// check (fixtureMatches, `node bench/perception-urls.mjs --check`) sees drift, and the drifted arm
// asserts that check says false while the real file says true.
test('his-data: control, the perception-urls.json line covers the file only through its generated-by clause and a writer that exists', async (t) => {
  const sources = path.join(ROOT, 'bench', 'fixtures', 'SOURCES.md');
  const fixture = path.join(ROOT, 'bench', 'fixtures', 'perception-urls.json');
  if (!existsSync(sources) || !existsSync(fixture)) { t.skip('bench/fixtures is never committed: this host has no SOURCES.md or no perception-urls.json'); return; }
  const { fixtureMatches } = await import('../bench/perception-urls.mjs');
  const realLines = readFileSync(sources, 'utf8').split(/\r?\n/);
  const idx = realLines.findIndex((l) => mentionsFile(l, 'perception-urls.json'));
  assert.ok(idx >= 0, 'the real SOURCES.md names the file');
  const real = realLines[idx];
  assert.ok(GENERATED_RE.test(real), 'the real line carries the clause the control removes');
  const fixtureText = readFileSync(fixture, 'utf8');
  const bytes = Buffer.byteLength(fixtureText);
  const ghost = 'bench/no-such-writer-his-data.mjs';
  assert.equal(existsSync(path.join(ROOT, ghost)), false, 'the ghost arm needs a writer that does not exist');
  const arms = {
    real: { line: real, text: fixtureText },
    noClause: { line: real.replace(GENERATED_RE, 'written by hand'), text: fixtureText },
    ghostWriter: { line: real.replace(GENERATED_RE, 'generated by node ' + ghost), text: fixtureText },
    drifted: { line: real, text: fixtureText.replace('"control"', '"controL"') },
  };
  assert.equal(GENERATED_RE.test(arms.noClause.line), false, 'the no-clause arm really has no clause');
  assert.notEqual(arms.drifted.text, fixtureText, 'the drifted arm really differs');
  const seen = {};
  for (const [name, arm] of Object.entries(arms)) {
    const root = mkdtempSync(path.join(tmpdir(), 'his-data-ctl-'));
    try {
      const lines = realLines.slice(); lines[idx] = arm.line;
      writeFileSync(path.join(root, 'SOURCES.md'), lines.join('\n'));
      writeFileSync(path.join(root, 'perception-urls.json'), arm.text);
      const cov = fixtureCoverage(root);
      assert.equal(cov.files, 1, name + ': the census sees one data file');
      const e = cov.list.find((x) => x.file === 'perception-urls.json');
      seen[name] = { covered: e.covered, licence: e.by ? e.by.licence : null, matches: fixtureMatches(path.join(root, 'perception-urls.json')), row: hisDataRow(cov, 'ctl').ok, uncoveredBytes: cov.uncoveredBytes };
    } finally { rmSync(root, { recursive: true, force: true }); }
  }
  assert.deepEqual(seen.real, { covered: true, licence: 'generated by bench/perception-urls.mjs', matches: true, row: true, uncoveredBytes: 0 });
  assert.deepEqual(seen.noClause, { covered: false, licence: null, matches: true, row: false, uncoveredBytes: bytes });
  assert.deepEqual(seen.ghostWriter, { covered: false, licence: null, matches: true, row: false, uncoveredBytes: bytes });
  // the census does not read bytes: a drifted fixture is still covered, and only the writer's check sees it
  assert.equal(seen.drifted.covered, true);
  assert.equal(seen.drifted.matches, false, 'the writer check sees the drift the census cannot');
});
