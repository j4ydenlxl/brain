function genDate(rng, i) {
  const fam = i % 6;
  // The years straddle 1900 and 2100, which are divisible by four and are not leap years.
  const someDate = () => {
    const y = 1890 + rng.int(220);
    const m = 1 + rng.int(12);
    const d = 1 + rng.int(28);
    return fmtDate(y, m, d);
  };
  const edge = ['1900-02-28', '2000-02-29', '2100-02-28', '1899-12-31', '2024-02-29'];
  if (fam === 0) {
    const cs = Array.from({ length: 7 }, (_, j) => (j < 2 ? [edge[j], edge[j + 2]] : [someDate(), someDate()]));
    return task('date.between.' + i, 'date', 'daysBetween', 'daysBetween(a, b)',
      'a and b are dates as the strings YYYY-MM-DD in the proleptic Gregorian calendar. Return the number of days from a to b, as a number, negative when b is earlier. There is no Date in the sandbox, so the calendar has to be computed: a year divisible by 4 is a leap year unless it is divisible by 100 and not by 400.',
      cs.map((args) => ({ args, expected: refDaysBetween(...args) })));
  }
  if (fam === 1) {
    const cs = Array.from({ length: 7 }, (_, j) => [j < edge.length ? edge[j] : someDate()]);
    return task('date.doy.' + i, 'date', 'dayOfYear', 'dayOfYear(a)',
      'a is a date as the string YYYY-MM-DD. Return its day of the year as a number, where the 1st of January is 1. There is no Date in the sandbox: a year divisible by 4 is a leap year unless it is divisible by 100 and not by 400.',
      cs.map((args) => ({ args, expected: refDayOfYear(...args) })));
  }
  if (fam === 2) {
    const cs = Array.from({ length: 7 }, (_, j) => [j < edge.length ? edge[j] : someDate()]);
    return task('date.weekday.' + i, 'date', 'weekdayIndex', 'weekdayIndex(a)',
      'a is a date as the string YYYY-MM-DD in the proleptic Gregorian calendar. Return the day of the week as a number where Sunday is 0 and Saturday is 6. There is no Date in the sandbox. The 1st of January 1970 was a Thursday.',
      cs.map((args) => ({ args, expected: refWeekdayIndex(...args) })));
  }
  if (fam === 3) {
    const cs = Array.from({ length: 7 }, (_, j) => [j < edge.length ? edge[j] : someDate(), -800 + rng.int(1600)]);
    return task('date.add.' + i, 'date', 'addDays', 'addDays(a, n)',
      'a is a date as the string YYYY-MM-DD. Return the date n days later, as a string in the same format with a four digit year and two digit month and day. n may be negative. There is no Date in the sandbox.',
      cs.map((args) => ({ args, expected: refAddDays(...args) })));
  }
  if (fam === 4) {
    const ys = [1900, 2000, 2100, 2024, 1899, 1600 + rng.int(500), 1600 + rng.int(500)];
    return task('date.leap.' + i, 'date', 'isLeap', 'isLeap(y)',
      'y is a year as a number. Return true when it is a leap year in the proleptic Gregorian calendar and false when it is not: divisible by 4, except that a year divisible by 100 is not a leap year unless it is also divisible by 400.',
      ys.map((y) => ({ args: [y], expected: refIsLeap(y) })));
  }
  const cs = Array.from({ length: 7 }, (_, j) => [j < edge.length ? edge[j] : someDate()]);
  return task('date.eom.' + i, 'date', 'endOfMonth', 'endOfMonth(a)',
    'a is a date as the string YYYY-MM-DD. Return the LAST day of that month, as a string in the same format. There is no Date in the sandbox, so February needs the leap year rule: divisible by 4, except a year divisible by 100 is not a leap year unless it is also divisible by 400.',
    cs.map((args) => ({ args, expected: refEndOfMonth(...args) })));
}

function genParser(rng, i) {
  const depth = 2 + (i % 3);
  const cs = [];
  const seen = new Set();
  while (cs.length < 7) {
    const e = genExprText(rng, depth);
    if (seen.has(e)) continue;
    seen.add(e);
    cs.push([e]);
  }
  return task('parser.eval.' + i, 'parser', 'evalExpr', 'evalExpr(src)',
    'src is an arithmetic expression over non negative integer literals with the binary operators + - * / , parentheses, and unary minus. Multiplication and division bind tighter than addition and subtraction, and operators of the same precedence group to the LEFT. Division truncates toward zero, so 7 / 2 is 3 and -7 / 2 is -3. Return the value as a number. There is no eval in the sandbox.',
    cs.map((args) => ({ args, expected: refEvalExpr(args[0]) })));
}

