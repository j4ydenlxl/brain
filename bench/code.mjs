export function verdictPathFor({ complete, barShaped }) {
  if (!complete) return barShaped ? VERDICTS.progress : VERDICTS.partial;
  return barShaped ? VERDICTS.bar : VERDICTS.partial;
}

// A run of the bar's shape is the whole fixture, every arm, and the fixture's own seed.
// Anything else measures something narrower and may not sit in the file named code.json.
// inMemory is one of those narrower things whatever its counts: tasks generated on a
// caller's seed are not the committed fixture, so a run over forty of them with all three
// arms still may not sit in the file that names the bar.
export function shapeOf({ tasksRun, tasksInFixture, armsRun, inMemory = false }) {
  const full = !inMemory && tasksRun === tasksInFixture && armsRun.length === 3;
  return {
    full,
    name: full ? 'full' : 'narrow',
    why: full ? null
      : (inMemory ? 'tasks generated in memory on a caller\'s seed, not bench/fixtures/code-tasks.json' : null)
        || (tasksRun !== tasksInFixture ? tasksRun + ' of the fixture\'s ' + tasksInFixture + ' tasks' : null)
        || 'arms ' + armsRun.join(','),
  };
}

// Is another process of this bench alive and claiming the bar? A dead pid's lock is stale
// and ignored. process.kill(pid, 0) throws ESRCH when nothing holds that pid.
function liveLock() {
  try {
    const l = JSON.parse(readFileSync(abs(VERDICTS.lock), 'utf8'));
    if (!Number.isInteger(l.pid) || l.pid === process.pid) return null;
    try { process.kill(l.pid, 0); } catch { return null; }
    return l;
  } catch { return null; }
}

