/**
 * Every task of the fixture: thirty generated from the seed, then the hand written ten.
 * @param {object} [opts] { seed }
 * @returns {object[]}
 */
export function buildTasks({ seed = DEFAULT_SEED } = {}) {
  const out = [];
  for (const kind of KINDS) {
    for (let i = 0; i < PER_KIND; i++) {
      const rng = new RNG('code/' + seed + '/' + kind + '/' + i);
      out.push(GENERATORS[kind](rng, i));
    }
  }
  for (const h of HAND) out.push(h);
  return out;
}

/** JSON with every non-ASCII character escaped, so the fixture is readable on any terminal. */
export function asciiJson(v) {
  // Written as a comparison on the code unit rather than a character class, so this file
  // itself stays ASCII and cannot be rewritten by a checkout that guesses an encoding.
  const s = JSON.stringify(v, null, 2);
  let out = '';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    out += c < 128 ? s[i] : '\\u' + c.toString(16).padStart(4, '0');
  }
  return out;
}


export function writeFixture(tasks, seed) {
  mkdirSync(path.dirname(FIXTURE), { recursive: true });
  const body = {
    generator: 'bench/code.mjs buildTasks({ seed })',
    seed,
    expectedFrom: {
      [GENERATED_FROM]: 'computed here by the reference implementation named in the task id, in full Node',
      [HAND_FROM]: 'written out by a person; no code produced these values',
    },
    ruler: 'a task counts when every hidden case passes; the visible cases are the only ones a model is ever shown',
    tasks,
  };
  writeFileSync(FIXTURE, asciiJson(body) + '\n');
  return FIXTURE;
}

export function loadFixture() {
  if (!existsSync(FIXTURE)) throw new Error('no fixture at ' + FIXTURE + ': run node bench/code.mjs --regenerate');
  return JSON.parse(readFileSync(FIXTURE, 'utf8'));
}

// ---------------------------------------------------------------- one arm, one task
function newAcc() { return { asked: 0, graded: 0, passed: 0, absent: 0, ms: [], rounds: [], hiddenPassed: 0, hiddenOf: 0, byKind: {}, reason: null }; }

function summarizeArm(acc, reason = null) {
  const byKind = {};
  for (const [k, v] of Object.entries(acc.byKind)) byKind[k] = { n: v.n, passed: v.n ? v.passed : null, accuracy: v.n ? r6(v.passed / v.n) : null };
  if (!acc.graded) {
    return {
      absent: true, reason: reason || acc.reason || 'no task was graded', asked: acc.asked, n: 0,
      passed: null, accuracy: null, interval: { lo: null, hi: null, width: null },
      meanRounds: null, meanMs: null, hiddenCasePassRate: null, byKind,
    };
  }
  return {
    absent: false, reason, asked: acc.asked, n: acc.graded, passed: acc.passed,
    accuracy: r6(acc.passed / acc.graded), interval: wilson(acc.passed, acc.graded),
    meanRounds: acc.rounds.length ? r2(mean(acc.rounds)) : null,
    meanMs: r2(mean(acc.ms)),
    hiddenCasePassRate: acc.hiddenOf ? r6(acc.hiddenPassed / acc.hiddenOf) : null,
    hiddenCases: { passed: acc.hiddenPassed, of: acc.hiddenOf },
    byKind,
  };
}

// ---------------------------------------------------------------- the run
export async function run(opts = {}) {
  const t0 = Date.now();
  const quiet = !!opts.quiet;
  const cfg = {
    model: opts.model || DEFAULT_MODEL,
    base: opts.base || OLLAMA_BASE,
    rounds: Number.isFinite(opts.rounds) ? opts.rounds : 3,
    probeMs: Number.isFinite(opts.probeMs) ? opts.probeMs : 1500,
    timeoutMs: Number.isFinite(opts.timeoutMs) ? opts.timeoutMs : 300_000,
    maxTokens: Number.isFinite(opts.maxTokens) ? opts.maxTokens : 1600,
    numCtx: Number.isFinite(opts.numCtx) ? opts.numCtx : 4096,
    limitMs: Number.isFinite(opts.limitMs) ? opts.limitMs : 2000,
    memoryMB: Number.isFinite(opts.memoryMB) ? opts.memoryMB : 128,
  };
  // inMemory generates the tasks here, on the caller's seed, and never reads or writes the
  // committed fixture. The daily ladder needs a different set of items every day; rewriting
  // the fixture to get them would move the bar's own tasks, so it does not touch the file.
  const inMemory = !!opts.inMemory;
  const seed = opts.seed === undefined || opts.seed === null || opts.seed === '' ? DEFAULT_SEED : String(opts.seed);
  const fixture = inMemory
    ? { seed, tasks: buildTasks({ seed }), from: 'bench/code.mjs buildTasks({ seed }), in memory' }
    : { ...loadFixture(), from: 'bench/fixtures/code-tasks.json' };
  let tasks = fixture.tasks;
  if (opts.kinds) {
    const want = String(opts.kinds).split(',').map((s) => s.trim()).filter(Boolean);
    tasks = tasks.filter((t) => want.includes(t.kind));
  }
  // A caller that has already chosen its items passes them by id. The order is the caller's,
  // because the draw rule that picked them is the caller's claim, not this file's.
  if (Array.isArray(opts.pick) && opts.pick.length) {
    const byId = new Map(tasks.map((t) => [t.id, t]));
    const missing = opts.pick.filter((id) => !byId.has(id));
    if (missing.length) throw new Error('--pick names ' + missing.length + ' task(s) this run does not hold: ' + missing.slice(0, 3).join(', '));
    tasks = opts.pick.map((id) => byId.get(id));
  }
  if (opts.limit > 0) tasks = tasks.slice(0, opts.limit);
  const selected = opts.arms ? String(opts.arms).split(',').map((s) => s.trim()).filter((a) => ARMS.includes(a)) : [...ARMS];
  if (!selected.length) throw new Error('--arms takes ' + ARMS.join(', ') + ' (comma separated)');
  const subset = selected.length < ARMS.length;
  const shape = shapeOf({ tasksRun: tasks.length, tasksInFixture: fixture.tasks.length, armsRun: selected, inMemory });
  // Two things can send a full shaped run to the partial file: another live run already
  // holds the bar, or the caller asked for the bar not to be touched. Both are recorded.
  const held = shape.full ? liveLock() : null;
  const barRefusal = !shape.full
    ? 'this run is ' + shape.why + ', which is not the bar\'s shape'
    : held ? 'pid ' + held.pid + ' started a run of the bar at ' + held.at + ' and is still alive' : null;
  const writesTheBar = opts.write !== false && !barRefusal;
  // The claim is taken BEFORE the first task, not at the end: a lock written after the loop
  // is not a lock, it is a receipt. A second bar run that starts now sees this pid alive and
  // demotes its own final write to the partial file instead of racing for code.json.
  if (writesTheBar) {
    mkdirSync(path.join(HERE, 'verdicts'), { recursive: true });
    writeFileSync(abs(VERDICTS.lock), JSON.stringify({ pid: process.pid, at: new Date().toISOString(), tasks: tasks.length }, null, 2));
  }
  const plan = planArms(tasks.length);
  const needsModel = selected.some((a) => a !== 'null');
  const up = needsModel ? await probeOllama(cfg.base, cfg.probeMs) : false;
  const downReason = 'no ollama at ' + cfg.base + ': /api/tags did not answer within ' + cfg.probeMs + ' ms';
  const notSelected = 'not selected: this run was --arms ' + selected.join(',');
  const acc = { organism: newAcc(), alone: newAcc(), null: newAcc() };
  if (needsModel && !up) { acc.organism.reason = downReason; acc.alone.reason = downReason; }
  for (const arm of ARMS) if (!selected.includes(arm)) acc[arm].reason = notSelected;

  if (!quiet) {
    console.log('\nCODE BENCH: the organism running its own candidates, the same model with one look, and no model at all, on '
      + tasks.length + ' tasks whose hidden cases no prompt ever carries.');
    console.log('arms ' + selected.join(',') + ', rounds ' + cfg.rounds + ', per case limit ' + cfg.limitMs + ' ms in a ' + cfg.memoryMB + ' MB worker');
    console.log(needsModel
      ? 'model ' + cfg.model + ' at ' + cfg.base + ', ollama ' + (up ? 'up' : 'DOWN, so the two model arms are absent') + '\n'
      : 'no model is wanted by this run: no arm here opens a socket\n');
  }

  const rows = [];
  for (let i = 0; i < tasks.length; i++) {
    const t = tasks[i];
    const row = { i, id: t.id, kind: t.kind, hidden: (t.hidden || []).length, order: plan[i].join('>'), arms: {} };
    for (const arm of plan[i]) {
      if (!selected.includes(arm)) { row.arms[arm] = { absent: true }; continue; }
      if (arm !== 'null' && !up) { row.arms[arm] = { absent: true }; continue; }
      const a = acc[arm];
      a.asked++;
      const r = await solveCode(t, {
        provider: arm === 'null' ? 'null' : 'ollama',
        rounds: arm === 'alone' ? 1 : cfg.rounds,
        model: arm === 'null' ? undefined : cfg.model,
        base: cfg.base, probeMs: cfg.probeMs, timeoutMs: cfg.timeoutMs,
        maxTokens: cfg.maxTokens, numCtx: cfg.numCtx,
        limitMs: cfg.limitMs, memoryMB: cfg.memoryMB,
      });
      if (r.absent) { a.absent++; if (!a.reason) a.reason = r.reason; row.arms[arm] = { absent: true, reason: r.reason }; continue; }
      a.graded++;
      a.ms.push(r.ms);
      a.rounds.push(r.rounds);
      a.hiddenPassed += r.hidden.passed; a.hiddenOf += r.hidden.all;
      if (r.ok) a.passed++;
      const b = a.byKind[t.kind] || (a.byKind[t.kind] = { n: 0, passed: 0 });
      b.n++; if (r.ok) b.passed++;
      const firstBad = (r.cases || []).find((c) => !c.ok) || null;
      row.arms[arm] = {
        ok: r.ok, rounds: r.rounds, candidates: r.candidates, solvedVisible: !!r.solvedVisible,
        hiddenPassed: r.hidden.passed, hiddenOf: r.hidden.all, ms: r2(r.ms), codeChars: r.codeChars,
        firstFailure: firstBad ? { args: firstBad.args, expected: firstBad.expected, got: firstBad.got, error: firstBad.error } : null,
      };
    }
    rows.push(row);
    // The verdict is rebuilt and written after EVERY task. A model arm costs minutes a task,
    // so a run killed halfway by a session limit or a machine would otherwise leave nothing
    // at all; this way it leaves the tasks it did measure, marked complete false.
    writeSnapshot(false);
    if (!quiet) {
      const cell = (arm) => {
        const c = row.arms[arm];
        if (c.absent) return arm + ' absent';
        return arm + ' ' + (c.ok ? 'ok ' : 'no ') + String(c.hiddenPassed) + '/' + String(c.hiddenOf)
          + ' r' + c.rounds + ' ' + String(r2(c.ms)).padStart(9) + 'ms';
      };
      console.log(String(i + 1).padStart(3) + ' ' + String(t.kind).padEnd(8) + String(t.id).padEnd(22)
        + plan[i].map(cell).join(' | '));
    }
  }

  // Declarations, so the loop above may call them: the file is built from what has been
  // measured so far and nothing else, whether that is 3 tasks or all 40.
  function snapshot(complete) {
    const arms = {};
    for (const arm of ARMS) arms[arm] = summarizeArm(acc[arm], acc[arm].reason);
    const present = ARMS.filter((a) => !arms[a].absent).sort((a, b) => arms[b].accuracy - arms[a].accuracy);
    const winner = present[0] || null, runner = present[1] || null;
    const gap = winner && runner ? r6(arms[winner].accuracy - arms[runner].accuracy) : null;
    const need = winner && runner ? nFor95(arms[winner].accuracy, arms[runner].accuracy) : null;
    const statement = winner && runner
      ? winner + ' won: ' + arms[winner].passed + '/' + arms[winner].n + ' = ' + (arms[winner].accuracy * 100).toFixed(2)
        + '% of tasks fully solved against ' + runner + ' ' + arms[runner].passed + '/' + arms[runner].n + ' = '
        + (arms[runner].accuracy * 100).toFixed(2) + '%, a gap of ' + (gap * 100).toFixed(2)
        + ' points. The 95% interval is ' + (arms[winner].interval.width * 100).toFixed(2) + ' points wide on the winner and '
        + (arms[runner].interval.width * 100).toFixed(2) + ' on the runner up, and a gap this size at these rates needs '
        + need + ' tasks per arm to separate from zero.'
      : winner
        ? winner + ' is the only arm that was graded: ' + arms[winner].passed + '/' + arms[winner].n
        : 'no arm was graded.';
    const checks = {
      everyTaskGotEverySelectedArm: rows.every((r) => selected.every((a) => r.arms[a] !== undefined)),
      everyTaskHadHiddenCases: tasks.every((t) => Array.isArray(t.hidden) && t.hidden.length > 0),
      everyTaskSaysWhereItsExpectedValuesCameFrom: tasks.every((t) => typeof t.expectedFrom === 'string' && t.expectedFrom.length > 0),
      armsRotated: plan.length < 2 || plan.some((p, i) => i > 0 && p[0] !== plan[i - 1][0]),
      theNullArmSpentNoRound: rows.every((r) => !r.arms.null || r.arms.null.absent || (r.arms.null.rounds === 0 && r.arms.null.candidates === 0)),
      absentArmsCarryAReason: ARMS.every((a) => !arms[a].absent || !!arms[a].reason),
      everyTaskWasReached: rows.length === tasks.length,
    };
    const green = Object.values(checks).every(Boolean);
    return {
      at: new Date().toISOString(), node: process.version,
      command: 'node bench/code.mjs' + (opts.model ? ' --model ' + opts.model : '')
        + (opts.rounds !== undefined ? ' --rounds ' + opts.rounds : '')
        + (opts.limit ? ' --limit ' + opts.limit : '')
        + (opts.kinds ? ' --kinds ' + opts.kinds : '')
        + (subset ? ' --arms ' + selected.join(',') : '')
        + (inMemory ? ' --seed ' + seed + ' (tasks generated in memory by the caller, not the fixture)' : ''),
      // GREEN is reserved for the bar. A narrow run that passes every structural check is
      // NARROW, not GREEN, because a GREEN in a file is what gets quoted as the bar.
      verdict: !complete ? 'PARTIAL' : (!green ? 'RED' : (barRefusal ? 'NARROW' : 'GREEN')),
      // The file says out loud what it is. A reader who finds isTheBar false has found a
      // narrower measurement, whatever its filename, and may not quote it as the bar.
      isTheBar: complete && !barRefusal,
      split: splitFor({ tasks: tasks.length, inMemory }),
      wroteTo: verdictPathFor({ complete, barShaped: !barRefusal }),
      notTheBarBecause: complete && barRefusal ? barRefusal : null,
      shape: { name: shape.name, tasksRun: tasks.length, tasksInFixture: fixture.tasks.length, armsRun: selected, inMemory },
      progress: { tasksDone: rows.length, tasksTotal: tasks.length, complete },
      checks, ms: Date.now() - t0,
      model: cfg.model, base: cfg.base, ollamaUp: needsModel ? up : null, armsRun: selected, rounds: cfg.rounds,
      sandbox: { limitMs: cfg.limitMs, memoryMB: cfg.memoryMB, maxTokens: cfg.maxTokens, numCtx: cfg.numCtx },
      tasks: {
        total: tasks.length, seed: fixture.seed, inMemory, fixture: fixture.from,
        byKind: tasks.reduce((m, t) => (m[t.kind] = (m[t.kind] || 0) + 1, m), {}),
        byExpectedFrom: tasks.reduce((m, t) => (m[t.expectedFrom] = (m[t.expectedFrom] || 0) + 1, m), {}),
        hiddenCases: tasks.reduce((n, t) => n + (t.hidden || []).length, 0),
        visibleCases: tasks.reduce((n, t) => n + (t.visible || []).length, 0),
      },
      ruler: 'a task counts when EVERY hidden case passes; hiddenCasePassRate is the generous edge and decides nothing',
      interleaving: 'task by task: all three arms answer task i before any arm sees task i+1, and the first arm rotates with i',
      armsDiffer: 'organism and alone use the same model, the same first prompt, the same extraction and the same sandbox; alone gets one call and no repair round',
      arms, winner, runnerUp: runner, gap, nFor95: need, statement, rows,
    };
  }
  // An in flight snapshot goes to code.progress.json and a finished one to the path its
  // SHAPE earns. Nothing here ever writes code.json mid run, so a run that dies at task 7
  // leaves the bar exactly as it found it and its own landing in the progress file.
  function writeSnapshot(complete) {
    const v = snapshot(complete);
    if (opts.write === false) return v;
    mkdirSync(path.join(HERE, 'verdicts'), { recursive: true });
    writeFileSync(abs(v.wroteTo), JSON.stringify(v, null, 2));
    // One live record: the landing is superseded the moment the finished file exists.
    if (v.wroteTo === VERDICTS.bar) { try { rmSync(abs(VERDICTS.progress)); } catch {} }
    return v;
  }

  const verdict = writeSnapshot(true);
  if (writesTheBar) { try { rmSync(abs(VERDICTS.lock)); } catch {} }
  const arms = verdict.arms, winner = verdict.winner, runner = verdict.runnerUp;
  const statement = verdict.statement;

  if (!quiet) {
    console.log('\n' + 'arm'.padEnd(10) + 'tasks'.padStart(6) + 'passed'.padStart(8) + 'accuracy'.padStart(10)
      + '95% width'.padStart(12) + 'mean rounds'.padStart(13) + 'mean ms'.padStart(11) + '  by kind');
    console.log('-'.repeat(104));
    for (const arm of ARMS) {
      const s = arms[arm];
      if (s.absent) { console.log(arm.padEnd(10) + 'absent: ' + s.reason); continue; }
      console.log(arm.padEnd(10) + String(s.n).padStart(6) + String(s.passed).padStart(8)
        + (s.accuracy * 100).toFixed(2).padStart(9) + '%' + (s.interval.width * 100).toFixed(2).padStart(11) + 'pp'
        + String(s.meanRounds).padStart(13) + String(s.meanMs).padStart(11) + '  '
        + Object.entries(s.byKind).map(([k, v]) => k + ' ' + v.passed + '/' + v.n).join(', '));
    }
    for (const arm of ARMS) {
      const s = arms[arm];
      if (s.absent || !s.hiddenCases) continue;
      console.log('   ' + arm + ': ' + s.hiddenCases.passed + ' of ' + s.hiddenCases.of
        + ' hidden cases passed (' + (s.hiddenCasePassRate * 100).toFixed(2) + '%), which is the generous edge and is not the ruler');
    }
    console.log('\n' + statement + '\n');
  }

  return verdict;
}

// ---------------------------------------------------------------- cli
// Every flag this bench answers to, and its kind. A flag that is not on this list is a
// TYPO OR A QUESTION, never an instruction to spend 44 minutes: `node bench/code.mjs --help`
// used to fall through this parser as {help: true} and run the entire bar over the file
// that holds the bar. Unknown now means bad, and bad now means nothing runs.
export const FLAGS = Object.freeze({
  model: 'string', base: 'string', kinds: 'string', arms: 'string', seed: 'string',
  rounds: 'number', limit: 'number', maxTokens: 'number', limitMs: 'number',
  timeoutMs: 'number', memoryMB: 'number', probeMs: 'number',
  quiet: 'bool', json: 'bool', nowrite: 'bool', regenerate: 'bool', help: 'bool',
  inMemory: 'bool',
});

export const USAGE = [
  'node bench/code.mjs [--model qwen3:1.7b] [--rounds 3] [--limit N] [--kinds a,b]',
  '                    [--arms organism,alone,null] [--seed s] [--inMemory] [--base url]',
  '                    [--maxTokens n] [--limitMs ms] [--timeoutMs ms] [--memoryMB n]',
  '                    [--probeMs ms] [--quiet] [--json] [--nowrite] [--regenerate] [--help]',
  '',
  'The full run, all ' + (PER_KIND * KINDS.length + 10) + ' tasks and all three arms, is the only shape that writes ' + VERDICTS.bar + '.',
  'Anything narrower writes ' + VERDICTS.partial + ' and its verdict reads NARROW.',
  'A run in flight writes ' + VERDICTS.progress + ' after every task and never the bar.',
].join('\n');

// Returns the parsed flags AND everything wrong with them; the caller decides, and the
// caller's decision is to run nothing when bad is not empty.
export function args(argv) {
  const out = {}, bad = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) { bad.push('stray argument ' + JSON.stringify(a)); continue; }
    const k = a.slice(2);
    const kind = FLAGS[k];
    if (!kind) { bad.push('unknown flag --' + k); continue; }
    const v = argv[i + 1];
    const bare = v === undefined || v.startsWith('--');
    if (kind === 'bool') { if (!bare) bad.push('--' + k + ' takes no value'); out[k] = true; continue; }
    if (bare) { bad.push('--' + k + ' needs a value'); continue; }
    i++;
    if (kind === 'number') {
      if (!/^-?\d+(\.\d+)?$/.test(v)) { bad.push('--' + k + ' needs a number, got ' + JSON.stringify(v)); continue; }
      out[k] = Number(v);
      continue;
    }
    out[k] = v;
  }
  return { opts: out, bad };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const parsed = args(process.argv.slice(2));
  const a = parsed.opts;
  if (parsed.bad.length) {
    // Nothing is run and nothing is written: the wrong word on the command line costs a
    // message, not the bar.
    console.error('bench/code.mjs ran nothing, because of ' + parsed.bad.length + ': ' + parsed.bad.join('; ') + '\n\n' + USAGE);
    process.exitCode = 2;
  } else if (a.help) {
    console.log(USAGE);
  } else if (a.regenerate) {
    const seed = a.seed === undefined ? DEFAULT_SEED : String(a.seed);
    const tasks = buildTasks({ seed });
    const file = writeFixture(tasks, seed);
    const byKind = tasks.reduce((m, t) => (m[t.kind] = (m[t.kind] || 0) + 1, m), {});
    console.log('REGENERATED ' + tasks.length + ' tasks into ' + file + ' at seed ' + seed
      + ': ' + Object.entries(byKind).map(([k, v]) => k + ' ' + v).join(', ')
      + '; hidden cases ' + tasks.reduce((n, t) => n + t.hidden.length, 0)
      + ', visible cases ' + tasks.reduce((n, t) => n + t.visible.length, 0));
  } else {
    // Every value here is already the right type or undefined: args() rejected the rest.
    const v = await run({
      model: a.model, base: a.base, rounds: a.rounds, limit: a.limit || 0,
      kinds: a.kinds, arms: a.arms, maxTokens: a.maxTokens, limitMs: a.limitMs,
      timeoutMs: a.timeoutMs, memoryMB: a.memoryMB, probeMs: a.probeMs,
      seed: a.seed, inMemory: !!a.inMemory,
      quiet: !!a.quiet, write: !a.nowrite,
    });
    if (a.json) console.log(JSON.stringify(v, null, 2));
    console.log('CODE ' + v.verdict + ': ' + v.statement + ' ' + v.ms + 'ms'
      + (a.nowrite ? ', nothing written (--nowrite)' : ', verdict written to ' + v.wroteTo)
      + (v.notTheBarBecause ? '. THIS IS NOT THE BAR: ' + v.notTheBarBecause : ''));
    // NARROW is an honest finish, not a failure: it says the run was smaller than the bar.
    if (v.verdict !== 'GREEN' && v.verdict !== 'NARROW') process.exitCode = 1;
  }
}
