// bench/code.mjs: THE CODE BENCH. The organism writes programs by running them, and it is
// measured against the same model doing the same job with one look and no run.
//
// Three arms, interleaved TASK BY TASK, never arm by arm: all three arms answer task i
// before any arm sees task i+1, and the first arm rotates with i, so a machine that gets
// busy halfway through moves every arm and not the one that happened to run then.
//
//   organism  act/code.mjs solveCode(), rounds 3: ask, RUN the candidate on the visible
//             cases, hand the failing case back, ask again. Then grade on the hidden cases.
//   alone     the identical first prompt, ONE model call, no run and no repair, graded on
//             the same hidden cases by the same runner. The two model arms differ in the
//             loop and in nothing else: same model, same prompt, same extraction, same
//             sandbox.
//   null      no model and no socket. The candidate is a function that returns undefined,
//             graded the same way. This is the floor, and it is what says how much of any
//             score is the task being easy to guess.
//
// ONE RULER: a task counts when EVERY hidden case passes. Partial credit is not reported as
// a score, because a function that gets three of four cases right is a function that does
// not work, and a bench that pays for it rewards the wrong thing.
//
// THE TASKS, bench/fixtures/code-tasks.json. Thirty are generated by the seeded generator in
// this file and their expected values come from the reference implementations in this file,
// which run in this process with the whole of Node available; the candidate runs in the
// pruned sandbox with almost none of it, which is the point of the kinds chosen: exact big
// integer arithmetic (the answer does not fit a double), string transforms over empty and
// non-BMP inputs (a surrogate pair is one character and two code units), array algorithms
// with off by one traps (one indexed, windows, lower bounds), day counts between dates (no
// Date in the sandbox, so the civil calendar has to be written out, leap centuries and all)
// and a small expression parser (precedence, parentheses, unary minus, division that
// truncates toward zero). Ten more are hand written and their expected values are typed into
// the fixture, marked expectedFrom "typed by hand into this fixture". --regenerate rewrites
// the file; the generator is deterministic, so a fixed seed reproduces every expected value,
// and test/code.test.mjs asserts exactly that against the committed fixture.
//
// THE HIDDEN CASES ARE NEVER IN A PROMPT. act/code.mjs builds every prompt from the spec,
// the signature and the visible cases. The score is a score on inputs the model never saw.
//
// IF OLLAMA IS DOWN the two model arms are recorded absent with the reason and their correct
// and accuracy are null. Zero would say the model answered and got everything wrong, which
// is a different measurement.
//
// THE BAR FILE IS WRITTEN ONCE, AT THE END, AND ONLY BY A RUN OF THE BAR'S SHAPE.
// bench/verdicts/code.json held the 40 task bar and was overwritten three times in one
// afternoon: by a smoke run of 3 tasks, by an --arms null run, and by a `--help` that this
// CLI used to swallow as an unknown flag and answer with the whole 44 minute bench. Each of
// those was a run of a DIFFERENT SHAPE writing to the one file that names the bar. So shape
// decides the path now. A run over the whole fixture with all three arms owns code.json;
// anything narrower owns code-partial.json; a run still in flight owns code.progress.json,
// which is what the "leave a measured landing" rule actually needs. An unknown flag runs
// nothing at all and exits 2.
//
// --inMemory GENERATES THE TASKS HERE, on --seed, and never reads or writes the fixture.
// The daily ladder needs different items every day; rewriting the fixture to get them would
// move the bar's own tasks. An in memory run is narrow by definition, whatever its counts.
//
//   node bench/code.mjs [--model qwen3:1.7b] [--rounds 3] [--limit N] [--kinds a,b]
//                       [--arms null] [--seed s] [--inMemory] [--base url] [--regenerate]
//                       [--maxTokens n] [--limitMs ms] [--quiet] [--json] [--nowrite]
//                       [--help]
