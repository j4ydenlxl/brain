const refMulAdd = (a, b, c) => (BigInt(a) * BigInt(b) + BigInt(c)).toString();
function refPowMod(b, e, m) {
  let base = BigInt(b) % BigInt(m), exp = BigInt(e), mod = BigInt(m), out = 1n;
  while (exp > 0n) {
    if (exp & 1n) out = (out * base) % mod;
    base = (base * base) % mod;
    exp >>= 1n;
  }
  return out.toString();
}
function refFib(n) {
  let a = 0n, b = 1n;
  for (let i = 0; i < n; i++) { const t = a + b; a = b; b = t; }
  return a.toString();
}
function refFactorialDigitSum(n) {
  let f = 1n;
  for (let i = 2n; i <= BigInt(n); i++) f *= i;
  let s = 0;
  for (const ch of f.toString()) s += Number(ch);
  return s;
}
function refBinomial(n, k) {
  let out = 1n;
  const kk = BigInt(Math.min(k, n - k));
  for (let i = 1n; i <= kk; i++) out = (out * (BigInt(n) - kk + i)) / i;
  return out.toString();
}
function refGcd(a, b) {
  let x = BigInt(a) < 0n ? -BigInt(a) : BigInt(a);
  let y = BigInt(b) < 0n ? -BigInt(b) : BigInt(b);
  while (y) { const t = x % y; x = y; y = t; }
  return x.toString();
}

const refReverseCodePoints = (s) => [...String(s)].reverse().join('');
const refToggleAscii = (s) => [...String(s)].map((c) => (c >= 'a' && c <= 'z' ? c.toUpperCase() : (c >= 'A' && c <= 'Z' ? c.toLowerCase() : c))).join('');
function refRunLength(s) {
  const cps = [...String(s)];
  let out = '', i = 0;
  while (i < cps.length) {
    let j = i;
    while (j < cps.length && cps[j] === cps[i]) j++;
    out += cps[i] + String(j - i);
    i = j;
  }
  return out;
}
const refCountCodePoint = (s, c) => [...String(s)].filter((x) => x === String(c)).length;
const refCollapseSpaces = (s) => String(s).replace(/\s+/g, ' ').trim();
const refCodePointLength = (s) => [...String(s)].length;

function refRotateLeft(xs, k) {
  const n = xs.length;
  if (!n) return [];
  const j = ((k % n) + n) % n;
  return xs.slice(j).concat(xs.slice(0, j));
}
function refKthLargest(xs, k) {
  const s = [...xs].sort((a, b) => b - a);
  return k >= 1 && k <= s.length ? s[k - 1] : null;
}
function refLongestRun(xs) {
  let best = 0, run = 0;
  for (let i = 0; i < xs.length; i++) {
    run = i > 0 && xs[i] === xs[i - 1] ? run + 1 : 1;
    if (run > best) best = run;
  }
  return best;
}
function refWindowSums(xs, w) {
  if (!(w >= 1) || w > xs.length) return [];
  const out = [];
  for (let i = 0; i + w <= xs.length; i++) {
    let s = 0;
    for (let j = i; j < i + w; j++) s += xs[j];
    out.push(s);
  }
  return out;
}
function refLowerBound(xs, x) {
  let lo = 0, hi = xs.length;
  while (lo < hi) { const mid = (lo + hi) >> 1; if (xs[mid] < x) lo = mid + 1; else hi = mid; }
  return lo;
}
const refDropEveryNth = (xs, n) => (n >= 1 ? xs.filter((_, i) => (i + 1) % n !== 0) : [...xs]);

function daysFromCivil(y, m, d) {
  const yy = y - (m <= 2 ? 1 : 0);
  const era = Math.floor(yy / 400);
  const yoe = yy - era * 400;
  const doy = Math.floor((153 * (m + (m > 2 ? -3 : 9)) + 2) / 5) + d - 1;
  const doe = yoe * 365 + Math.floor(yoe / 4) - Math.floor(yoe / 100) + doy;
  return era * 146097 + doe - 719468;
}
function civilFromDays(z0) {
  const z = z0 + 719468;
  const era = Math.floor(z / 146097);
  const doe = z - era * 146097;
  const yoe = Math.floor((doe - Math.floor(doe / 1460) + Math.floor(doe / 36524) - Math.floor(doe / 146096)) / 365);
  const y = yoe + era * 400;
  const doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  const mp = Math.floor((5 * doy + 2) / 153);
  const d = doy - Math.floor((153 * mp + 2) / 5) + 1;
  const m = mp + (mp < 10 ? 3 : -9);
  return [y + (m <= 2 ? 1 : 0), m, d];
}
const parseDate = (s) => String(s).split('-').map(Number);
const pad = (n, w) => String(n).padStart(w, '0');
const fmtDate = (y, m, d) => pad(y, 4) + '-' + pad(m, 2) + '-' + pad(d, 2);
const refDaysBetween = (a, b) => daysFromCivil(...parseDate(b)) - daysFromCivil(...parseDate(a));
const refDayOfYear = (a) => { const [y, m, d] = parseDate(a); return daysFromCivil(y, m, d) - daysFromCivil(y, 1, 1) + 1; };
const refWeekdayIndex = (a) => { const z = daysFromCivil(...parseDate(a)); return ((z + 4) % 7 + 7) % 7; };
const refAddDays = (a, n) => fmtDate(...civilFromDays(daysFromCivil(...parseDate(a)) + n));
const refIsLeap = (y) => (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
function refEndOfMonth(a) {
  const [y, m] = parseDate(a);
  const ny = m === 12 ? y + 1 : y, nm = m === 12 ? 1 : m + 1;
  return fmtDate(...civilFromDays(daysFromCivil(ny, nm, 1) - 1));
}

/**
 * The expression language, defined by this function: integers, + - * / with the usual
 * precedence, parentheses, unary minus, and division that truncates toward zero.
 */
export function refEvalExpr(src) {
  const s = String(src);
  let i = 0;
  const skip = () => { while (i < s.length && s[i] === ' ') i++; };
  function primary() {
    skip();
    if (s[i] === '(') { i++; const v = expr(); skip(); if (s[i] === ')') i++; return v; }
    if (s[i] === '-') { i++; return -primary(); }
    const j = i;
    while (i < s.length && s[i] >= '0' && s[i] <= '9') i++;
    return Number(s.slice(j, i));
  }
  function term() {
    let v = primary();
    for (;;) {
      skip();
      if (s[i] === '*') { i++; v = v * primary(); continue; }
      if (s[i] === '/') { i++; v = Math.trunc(v / primary()); continue; }
      return v;
    }
  }
  function expr() {
    let v = term();
    for (;;) {
      skip();
      if (s[i] === '+') { i++; v = v + term(); continue; }
      if (s[i] === '-') { i++; v = v - term(); continue; }
      return v;
    }
  }
  return expr();
}

