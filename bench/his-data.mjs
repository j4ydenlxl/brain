// bench/his-data.mjs: the HIS DATA row on its own, printed and written to bench/verdicts/his-data.json.
//
// The gate (bench/gate.mjs) prints this row among its others; running the whole gate to read one row
// is forbidden under the board budget rule, so this file computes the same row through the gate's own
// exported fixtureCoverage and hisDataRow, prints the line the gate would print, and writes the verdict
// (isTheBar true, barMet when the row is GREEN; a provenance census has no held-out data).
//
// Usage: node bench/his-data.mjs [--dir bench/fixtures] [--out bench/verdicts/his-data.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fixtureCoverage, hisDataRow } from './gate.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const arg = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] != null ? argv[i + 1] : d; };

/** Compute the row and the verdict object for a fixtures directory. */
export function hisDataVerdict(dir = 'bench/fixtures') {
  const cov = fixtureCoverage(path.resolve(ROOT, dir));
  const row = hisDataRow(cov, dir);
  const by = Object.entries(cov.byLicence).map(([k, v]) => ({ licence: k, files: v }));
  const generated = cov.list.filter((x) => x.covered && x.by.generated).map((x) => ({ file: x.file, writer: x.by.licence.replace(/^generated by /, ''), bytes: x.bytes }));
  const statement = 'The HIS DATA row asks that every byte under ' + dir + ' be public data with a named licence or data the tree writes itself, so that the bytes of the owner\'s own hand-typed data are 0. '
    + 'The census read ' + cov.files + ' data files (' + cov.bytes + ' bytes) and ' + cov.notice.length + ' notice files; ' + cov.covered + ' files (' + cov.coveredBytes + ' bytes) are covered, '
    + cov.uncovered.length + ' (' + cov.uncoveredBytes + ' bytes) are not' + (cov.uncovered.length ? ': ' + cov.uncovered.map((u) => u.file).join(', ') : '') + '. '
    + 'Covered by a tree writer: ' + generated.length + ' files' + (generated.length ? ' (' + generated.map((g) => g.file + ' by ' + g.writer).join(', ') + ')' : '') + '. '
    + 'The row is ' + (row.ok ? 'GREEN' : 'RED') + '.';
  return {
    at: new Date().toISOString(), command: 'node bench/his-data.mjs --dir ' + dir, node: process.version,
    isTheBar: true, barMet: row.ok, line: row.line,
    row: { ok: row.ok, files: row.files, covered: row.covered, bytes: row.bytes, uncovered: row.uncovered, uncoveredBytes: row.uncoveredBytes, notice: row.notice, sources: row.sources, byLicence: by, generated },
    split: { development: 'every file under ' + dir + ' and every SOURCES.md line there (a census of provenance, not a model)', heldOut: 'none', why: 'a provenance census reads every file once; nothing is trained or tuned, so there is no held-out data to keep apart', contaminated: false },
    statement,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = arg('dir', 'bench/fixtures');
  const out = path.resolve(ROOT, arg('out', 'bench/verdicts/his-data.json'));
  const v = hisDataVerdict(dir);
  console.log(v.line);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, JSON.stringify(v, null, 2) + '\n');
  console.log('wrote ' + path.relative(ROOT, out).replaceAll('\\', '/') + ' barMet ' + v.barMet);
}
