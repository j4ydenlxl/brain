// tools/numbers.mjs: every number the research plan, the poster and the site may quote,
// read from bench/verdicts/*.json (the only place a number is allowed to come from).
// Prints a markdown table and writes docs/NUMBERS.md so no document carries a figure
// that no command printed. Run: node tools/numbers.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'bench', 'verdicts');

// Walk a verdict object and pull out (path, number) pairs, bounded so a big table
// (per cell results) does not flood the page.
function leaves(obj, prefix = '', out = [], depth = 0) {
  if (depth > 4 || out.length > 400) return out;
  if (Array.isArray(obj)) {
    if (obj.length > 6) { out.push([prefix + '.length', obj.length]); return out; }
    obj.forEach((v, i) => leaves(v, prefix + '[' + i + ']', out, depth + 1));
    return out;
  }
  if (obj && typeof obj === 'object') {
    for (const [k, v] of Object.entries(obj)) leaves(v, prefix ? prefix + '.' + k : k, out, depth + 1);
    return out;
  }
  if (typeof obj === 'number' && Number.isFinite(obj)) out.push([prefix, obj]);
  else if (typeof obj === 'string' && /^(GREEN|RED|PASS|FAIL)$/.test(obj)) out.push([prefix, obj]);
  return out;
}

const rows = [];
for (const name of readdirSync(DIR).filter(n => n.endsWith('.json')).sort()) {
  let j;
  try { j = JSON.parse(readFileSync(path.join(DIR, name), 'utf8')); } catch (e) { rows.push([name, 'unreadable', String(e.message)]); continue; }
  const at = j.at || j.when || '';
  for (const [k, v] of leaves(j)) rows.push([name.replace(/\.json$/, ''), k, typeof v === 'number' ? (Number.isInteger(v) ? String(v) : v.toPrecision(6)) : v, at]);
}

const lines = ['# Numbers (generated by tools/numbers.mjs, never typed by hand)', '',
  'Source: bench/verdicts/*.json. Regenerate with `node tools/numbers.mjs`. A figure that is not in this table may not appear in any document, poster or page.', '',
  '| bench | measure | value | measured at |', '|---|---|---|---|'];
for (const r of rows) lines.push('| ' + r.join(' | ') + ' |');
writeFileSync(path.join(ROOT, 'docs', 'NUMBERS.md'), lines.join('\n') + '\n');
console.log(lines.slice(0, 8).join('\n'));
console.log(`... ${rows.length} rows from ${new Set(rows.map(r => r[0])).size} verdict files written to docs/NUMBERS.md`);
