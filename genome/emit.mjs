// genome/emit.mjs: WRITE THE ORGANISM AS SOURCE.
//
// A brain that exists only as the output of a builder is a brain nobody can read, diff,
// review or hand to someone else. This writes one out as ES modules: one `c(...)` call per
// cell and one `e(...)` call per edge, one per line, split into files of at most 20,000
// lines, plus a `regions.mjs` that declares the regions and circuits, an `index.mjs` that
// imports them in order and exports `load()`, and a `manifest.json` with the counts and a
// content hash over every one of those lines.
//
// The emitted source is the genome: structure, parameters, policy, weights, delays. It is
// not a snapshot. Runtime state, mailboxes, the clock and the ledger belong to
// Brain.snapshot; the genome is what the organism IS, the snapshot is where it HAD GOT TO.
//
// Weights and delays are exact. Connectome.w and .conf are Float32Array, and f32() prints
// the shortest decimal that Math.fround reads back to the identical float32, so loading the
// emitted source reproduces the connectome bit for bit and the content hash agrees.
import { mkdirSync, writeFileSync, rmSync, renameSync, existsSync, readFileSync, openSync, readSync, closeSync, readdirSync, statSync, cpSync } from 'node:fs';
import { StringDecoder } from 'node:string_decoder';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { f32, stable, contentHash, Wiring, monomorphicGrowth } from './wire.mjs';
import { getKind, DEFAULT_POLICY } from '../core/cell.mjs';
import { Brain } from '../core/brain.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BRAIN_ROOT = path.resolve(HERE, '..');
export const DEFAULT_SPLIT = 20000;

/**
 * Write a brain out as source.
 * @param {object} brain
 * @param {object} [opts]
 * @param {string} [opts.dir] output directory, default brain/organism/<brain.name>
 * @param {number} [opts.split] maximum physical lines per emitted file
 * @param {boolean} [opts.clean] remove the directory first, default true
 * @returns {{ dir, files, lines, bytes, counts, hash, manifest }}
 */
export function emitOrganism(brain, { dir = null, split = DEFAULT_SPLIT, clean = true, prune = null } = {}) {
  // prune is opt in and off by default: { cells, edges } liveness readers from readLiveBits,
  // plus pruneBrain's options. Without it the brain is written exactly as before.
  if (prune) brain = pruneBrain(brain, prune, prune).brain;
  const name = brain.name;
  const out = dir ? path.resolve(dir) : path.join(BRAIN_ROOT, 'organism', name);
  if (clean && existsSync(out)) rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const genome = brain.genome || {};
  const k = brain.connectome;
  const files = [];
  const write = (file, lines) => {
    const text = lines.join('\n') + '\n';
    writeFileSync(path.join(out, file), text);
    // Counted exactly the way bench/gate.mjs counts: physical lines of the file as written.
    const n = text.split('\n').length;
    files.push({ path: file, lines: n, bytes: Buffer.byteLength(text), sha256: createHash('sha256').update(text).digest('hex') });
    return n;
  };

  // ------------------------------------------------------------ regions.mjs
  {
    const L = [
      '// ' + name + '/regions.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// The regions of the organism and the circuits inside them. A circuit is a major',
      '// computational node: ' + brain.circuits.size + ' of them here, across ' + brain.regions.size + ' regions.',
      '// r(name, { budget, doc }); budget null means unbounded. k(region, name, period, doc).',
      'export default function regions(r, k) {',
    ];
    for (const rg of brain.regions.values()) {
      L.push('r(' + J(rg.name) + ',{"budget":' + (Number.isFinite(rg.budget) ? rg.budget : 'null') + ',"doc":' + J(rg.doc || '') + '});');
    }
    for (const c of brain.circuits.values()) {
      L.push('k(' + J(c.region) + ',' + J(c.name) + ',' + J(c.period) + ',' + J(c.doc || '') + ');');
    }
    L.push('}');
    if (L.length + 1 > split) throw new Error('emit: regions.mjs would be ' + (L.length + 1) + ' lines, over the ' + split + ' line split');
    write('regions.mjs', L);
  }

  // ------------------------------------------------------------ cells-NNN.mjs
  const cellFiles = emitChunks({
    write, split, prefix: 'cells', total: brain.cells.length,
    head: (i, lo, hi) => [
      '// ' + name + '/cells-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// Cells ' + lo + ' to ' + (hi - 1) + ' of ' + brain.cells.length + '.',
      '// c(id, kind, region, circuit, params, policy)',
      'export default function cells(c) {',
    ],
    line: (i) => {
      const c = brain.cells[i];
      return 'c(' + J(c.id) + ',' + J(c.kind) + ',' + J(c.region) + ',' + J(c.circuit) + ',' + JSON.stringify(c.params) + ',' + JSON.stringify(c.policy) + ');';
    },
  });

  // ------------------------------------------------------------ edges-NNN.mjs
  const edgeFiles = emitChunks({
    write, split, prefix: 'edges', total: k.n,
    head: (i, lo, hi) => [
      '// ' + name + '/edges-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// Edges ' + lo + ' to ' + (hi - 1) + ' of ' + k.n + '. THE CONNECTOME IS THE BULK OF THE ORGANISM.',
      '// e(src, dst, srcPort, dstPort, w, delay, conf); conf is omitted when it is the 0.5 default.',
      'export default function edges(e) {',
    ],
    line: (i) => {
      const conf = Math.fround(k.conf[i]);
      return 'e(' + J(brain.cells[k.src[i]].id) + ',' + J(brain.cells[k.dst[i]].id) + ',' + k.srcPort[i] + ',' + k.dstPort[i] +
        ',' + f32(k.w[i]) + ',' + k.delay[i] + (conf === 0.5 ? '' : ',' + f32(conf)) + ');';
    },
  });

  // ------------------------------------------------------------ index.mjs
  const hash = contentHash(brain);
  const counts = {
    regions: brain.regions.size, circuits: brain.circuits.size,
    cells: brain.cells.length, edges: k.n,
    cellFiles: cellFiles.length, edgeFiles: edgeFiles.length,
  };
  {
    const rel = toPosix(path.relative(out, BRAIN_ROOT)) || '.';
    const L = [
      '// ' + name + '/index.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// The organism as source. load() returns a Brain wired exactly as it was emitted.',
      'import { loadOrganism } from ' + J(rel + '/genome/load.mjs') + ';',
      'import regions from ' + J('./regions.mjs') + ';',
    ];
    for (const f of cellFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    for (const f of edgeFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    L.push('');
    L.push('export const meta = ' + JSON.stringify({ name, seed: genome.seed ?? name, genome, counts, hash }) + ';');
    L.push('export const parts = { regions, cells: [' + cellFiles.map(ident).join(', ') + '], edges: [' + edgeFiles.map(ident).join(', ') + '] };');
    L.push('export function load(opts = {}) { return loadOrganism(parts, meta, opts); }');
    L.push('export default load;');
    write('index.mjs', L);
  }

  // ------------------------------------------------------------ manifest.json
  const lines = files.reduce((a, f) => a + f.lines, 0);
  const bytes = files.reduce((a, f) => a + f.bytes, 0);
  const manifest = {
    format: 'brain.genome.v1',
    name, seed: genome.seed ?? name, genome,
    counts: { ...counts, files: files.length + 1, lines, bytes },
    hash,
    files: files.slice().sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0),
  };
  const mtext = JSON.stringify(manifest, null, 2) + '\n';
  writeFileSync(path.join(out, 'manifest.json'), mtext);
  manifest.counts.lines += mtext.split('\n').length;

  return { dir: out, files: manifest.files, lines: manifest.counts.lines, bytes, counts, hash, manifest };
}

// Write `total` lines in chunks that never exceed `split` physical lines per file.
function emitChunks({ write, split, prefix, total, head, line }) {
  const names = [];
  const probe = head(0, 0, 0);
  const perFile = Math.max(1, split - probe.length - 2); // head lines, the closing brace, the final newline
  let file = 0;
  for (let lo = 0; lo < total || file === 0; lo += perFile, file++) {
    const hi = Math.min(total, lo + perFile);
    const L = head(file, lo, hi);
    for (let i = lo; i < hi; i++) L.push(line(i));
    L.push('}');
    const nm = prefix + '-' + pad3(file) + '.mjs';
    write(nm, L);
    names.push(nm);
    if (hi >= total) break;
  }
  return names;
}

const J = (v) => JSON.stringify(v);
const pad3 = (n) => String(n).padStart(3, '0');
const toPosix = (p) => p.replaceAll('\\', '/');
const ident = (file) => file.replace(/\.mjs$/, '').replace(/[^A-Za-z0-9]/g, '_');

// ---------------------------------------------------------------- prune (MANUAL P8)
//
// A census (tools/organism-census.mjs) loads an emitted organism, drives it, and records
// which declared cells ran at least once and which declared edges delivered at least once.
// It writes that liveness as two bitsets, one bit per cell and one bit per edge, in load
// order. Load order is line order: loadOrganism replays the c() lines and e() lines in the
// order the files list them, Wiring.add appends each accepted edge at the next index, and an
// emitted organism carries no duplicate edge (the census refuses a seed whose reload reports
// one, because then the line to index mapping would be off by the duplicates).
//
// pruneBrain copies a brain keeping every declaration the census saw do something: every
// cell that ran (a cell that fired ran), every edge that delivered, every edge still carrying
// a signal at the end when the census recorded those, both endpoints of every kept edge (a
// cell that never ran but received a delivery is kept, so a delivered edge is never dropped
// for want of an endpoint), every declaration the caller protects (the cells the hosted
// problems ran on, and every declaration of a file whose knockout lowered a hosted score),
// and the regions and circuits that still hold a kept cell. What goes is only what never ran
// and never delivered. The copy is then written by the same emitOrganism above, so the
// pruned seed is loaded by the same loader and checked by the same verify() as any other.

/**
 * Encode liveness as a bitset: bit i set when isLive(i).
 * @param {number} n @param {(i:number)=>boolean} isLive
 * @returns {{ n: number, count: number, encoding: string, b64: string }}
 */
export function liveBits(n, isLive) {
  const bytes = new Uint8Array((n + 7) >> 3);
  let count = 0;
  for (let i = 0; i < n; i++) if (isLive(i)) { bytes[i >> 3] |= 1 << (i & 7); count++; }
  return { n, count, encoding: 'bitset, bit i of byte i>>3 at position i&7, base64', b64: Buffer.from(bytes).toString('base64') };
}

/**
 * Decode a liveBits object and check it: the popcount must equal the recorded count.
 * @param {{ n: number, count: number, b64: string }} o
 * @returns {{ n: number, count: number, has: (i:number)=>boolean }}
 */
export function readLiveBits(o) {
  if (!o || !Number.isInteger(o.n) || typeof o.b64 !== 'string') throw new Error('prune: liveness is not a liveBits object');
  const bytes = Buffer.from(o.b64, 'base64');
  if (bytes.length !== ((o.n + 7) >> 3)) throw new Error('prune: liveness holds ' + bytes.length + ' bytes for ' + o.n + ' bits');
  let count = 0;
  for (let i = 0; i < o.n; i++) if ((bytes[i >> 3] >> (i & 7)) & 1) count++;
  if (count !== o.count) throw new Error('prune: liveness popcount ' + count + ' does not match its recorded count ' + o.count);
  return { n: o.n, count, has: (i) => ((bytes[i >> 3] >> (i & 7)) & 1) === 1 };
}

/**
 * Copy a brain keeping only what a census found alive.
 * @param {object} brain a freshly loaded organism (never ticked: params are copied as they are)
 * @param {{ cells: {n, has}, edges: {n, has}, inFlight?: {n, has} }} live readers from readLiveBits
 * @param {object} [opts] { name, note, protect: { cells: Iterable<idx>, edges: Iterable<idx>, why } }
 * @returns {{ brain: object, dropped: object, kept: object }}
 */
export function pruneBrain(brain, live, { name = null, note = null, protect = null } = {}) {
  const k = brain.connectome;
  if (!live || !live.cells || !live.edges) throw new Error('prune: need { cells, edges } liveness');
  if (live.cells.n !== brain.cells.length) throw new Error('prune: liveness covers ' + live.cells.n + ' cells, the brain has ' + brain.cells.length);
  if (live.edges.n !== k.n) throw new Error('prune: liveness covers ' + live.edges.n + ' edges, the brain has ' + k.n);
  if (live.inFlight && live.inFlight.n !== k.n) throw new Error('prune: in flight liveness covers ' + live.inFlight.n + ' edges, the brain has ' + k.n);
  const { loaded, hash, wiring, pruned: priorPrune, ...genome } = brain.genome || {};
  const runtime = genome.runtime || {};
  const outName = name || brain.name + '-pruned';
  const out = new Brain({
    name: outName, seed: genome.seed ?? brain.name,
    ledger: 'off', pruneEvery: 0, ...runtime,
    policy: monomorphicGrowth(runtime.gate || {}),
  });

  // what is kept: ran, delivered, in flight, protected, and the endpoints of every kept edge
  const nC = brain.cells.length;
  const keepCell = new Uint8Array(nC), keepEdge = new Uint8Array(k.n);
  const protCells = new Uint8Array(nC), protEdges = new Uint8Array(k.n);
  for (const i of (protect && protect.cells) || []) { if (!(i >= 0 && i < nC)) throw new Error('prune: protected cell ' + i + ' is out of range'); protCells[i] = 1; }
  for (const e of (protect && protect.edges) || []) { if (!(e >= 0 && e < k.n)) throw new Error('prune: protected edge ' + e + ' is out of range'); protEdges[e] = 1; }
  let cellsRan = 0, cellsProtectedOnly = 0, cellsEndpointOnly = 0, edgesDelivered = 0, edgesInFlightOnly = 0, edgesProtectedOnly = 0;
  for (let i = 0; i < nC; i++) {
    if (live.cells.has(i)) { keepCell[i] = 1; cellsRan++; }
    else if (protCells[i]) { keepCell[i] = 1; cellsProtectedOnly++; }
  }
  for (let e = 0; e < k.n; e++) {
    if (live.edges.has(e)) { keepEdge[e] = 1; edgesDelivered++; }
    else if (live.inFlight && live.inFlight.has(e)) { keepEdge[e] = 1; edgesInFlightOnly++; }
    else if (protEdges[e]) { keepEdge[e] = 1; edgesProtectedOnly++; }
    else continue;
    for (const i of [k.src[e], k.dst[e]]) if (!keepCell[i]) { keepCell[i] = 1; cellsEndpointOnly++; }
  }
  const liveRegions = new Set(), liveCircuits = new Set();
  for (let i = 0; i < nC; i++) {
    if (!keepCell[i]) continue;
    const c = brain.cells[i];
    liveRegions.add(c.region); liveCircuits.add(c.region + '/' + c.circuit);
  }
  let regionsDropped = 0, circuitsDropped = 0;
  for (const rg of brain.regions.values()) {
    if (liveRegions.has(rg.name)) out.addRegion(rg.name, { budget: rg.budget, doc: rg.doc || '' }); else regionsDropped++;
  }
  for (const c of brain.circuits.values()) {
    if (liveCircuits.has(c.region + '/' + c.name)) out.addCircuit(c.region, c.name, { period: c.period, doc: c.doc || '' }); else circuitsDropped++;
  }
  const newIdx = new Int32Array(brain.cells.length).fill(-1);
  for (let i = 0; i < brain.cells.length; i++) {
    if (!keepCell[i]) continue;
    const c = brain.cells[i];
    newIdx[i] = out.addCell({ id: c.id, kind: c.kind, region: c.region, circuit: c.circuit, params: JSON.parse(JSON.stringify(c.params)), policy: JSON.parse(JSON.stringify(c.policy)) }).idx;
  }
  const wiringOut = new Wiring(out, { reserve: edgesDelivered + edgesInFlightOnly + edgesProtectedOnly, strict: true });
  let edgesDead = 0, orphaned = 0;
  for (let e = 0; e < k.n; e++) {
    if (!keepEdge[e]) { edgesDead++; continue; }
    const a = newIdx[k.src[e]], z = newIdx[k.dst[e]];
    if (a < 0 || z < 0) { orphaned++; continue; }
    wiringOut.add(a, z, k.srcPort[e], k.dstPort[e], { w: k.w[e], delay: k.delay[e], conf: k.conf[e] });
  }
  wiringOut.finish();
  // a kept edge always keeps both endpoints, so nothing can be orphaned; say so if it ever is
  if (orphaned) throw new Error('prune: ' + orphaned + ' kept edges lost an endpoint');
  const dropped = {
    cells: nC - out.cells.length, edgesNeverDelivered: edgesDead, edgesOrphaned: 0,
    edges: k.n - out.connectome.n, regions: regionsDropped, circuits: circuitsDropped,
  };
  const kept = {
    cells: { ran: cellsRan, protectedOnly: cellsProtectedOnly, endpointOnly: cellsEndpointOnly },
    edges: { delivered: edgesDelivered, inFlightOnly: edgesInFlightOnly, protectedOnly: edgesProtectedOnly, inFlightRecorded: !!live.inFlight },
    protect: { cells: protCells.reduce((a, b) => a + b, 0), edges: protEdges.reduce((a, b) => a + b, 0), why: (protect && protect.why) || [] },
  };
  // the latest round at the top (what the last prune did, where the census reads it), every round
  // kept in order under rounds: a prune of a pruned seed used to drop the record of the first one
  const round = {
    from: brain.name, fromHash: hash ?? null,
    cells: { before: nC, after: out.cells.length },
    edges: { before: k.n, after: out.connectome.n, neverDelivered: edgesDead, orphaned: 0 },
    kept,
    regionsDropped, circuitsDropped, wiring: { added: wiringOut.added, duplicates: wiringOut.duplicates, illegal: wiringOut.illegal },
    ...(note ? { census: note } : {}),
  };
  const prior = priorPrune ? (Array.isArray(priorPrune.rounds) ? priorPrune.rounds : [(({ rounds, ...r }) => r)(priorPrune)]) : [];
  out.genome = { ...genome, name: outName, pruned: { ...round, rounds: [...prior, round] } };
  return { brain: out, dropped, kept };
}

// ---------------------------------------------------------------- wire before prune (MANUAL P8, Board 23)
//
// "the emitter prunes what never runs or wires it so it runs". A prune alone deletes a line; it
// does not make one important. So before the prune, the emitter WIRES: a census names every
// port that delivered (a cell fired on it and an edge carried the signal inside the horizon),
// and every in port no delivered edge reached. A silent cell (no out edge of it delivered) that
// can still read mail inside the horizon, with an in port nothing reached, gets ONE edge from a
// port that delivered and that the in port legally accepts: the same subset rule and the same
// monomorphic claim the builder and the loader enforce (genome/wire.mjs), the donor edge's own
// weight, delay and confidence (so the new edge arrives when a delivered one did), and the donor
// nearest in the organism (same circuit, then same region, then any; then the nearest index).
// The published shape is prune and regrow (SET, Mocanu et al. 2018) after an activation census
// (Network Trimming, Hu et al. 2016): regrow where a live source can reach, prune the rest.
//
// What is never wired: a cell the hosted problems ran on (its answers are read through a tap,
// and extra mail would change them), a cell that already delivered (it works; its inputs are
// left alone), and a periodic cell whose next run after tick 0 is past the horizon (mail it
// gets is never read). The rule adds edges only; no declaration is changed or removed, so the
// wired seed's first n edges are the original n in the original order. The census of the wired
// seed is what the prune then reads: whatever still never runs or delivers is what nothing
// reaches, and it goes.

/**
 * Wire every silent cell's unreached in ports from ports that delivered.
 * @param {object} brain a freshly loaded organism (never ticked); edges are appended to it
 * @param {{ cells: {n, has}, edges: {n, has} }} live readers from readLiveBits
 * @param {{ horizon: number, protect?: Iterable<number>, note?: object }} opts horizon is the
 *   census's last tick bound (census.dormant.lastTickBound); protect the hosted cell indexes
 * @returns {{ brain, wired: Array<object>, counts: object }}
 */
export function wireBrain(brain, live, { horizon, protect = [], note = null } = {}) {
  const k = brain.connectome, nC = brain.cells.length, nE = k.n;
  if (!live || !live.cells || !live.edges) throw new Error('wire: need { cells, edges } liveness');
  if (live.cells.n !== nC) throw new Error('wire: liveness covers ' + live.cells.n + ' cells, the brain has ' + nC);
  if (live.edges.n !== nE) throw new Error('wire: liveness covers ' + live.edges.n + ' edges, the brain has ' + nE);
  if (!(Number.isInteger(horizon) && horizon > 0)) throw new Error('wire: need the census horizon (its last tick bound), got ' + horizon);
  const prot = new Uint8Array(nC);
  for (const i of protect) { if (!(i >= 0 && i < nC)) throw new Error('wire: protected cell ' + i + ' is out of range'); prot[i] = 1; }
  // what delivered: per cell, whether any out edge delivered; per in port, whether any edge into it did;
  // the donor ports (cell, out port) with the first delivered edge on each; the claim of every in port
  const delivers = new Uint8Array(nC), reached = new Set(), donorEdge = new Map(), claim = new Map(), have = new Set();
  const portKeyOf = (c, sp) => { const o = c.ports.out[sp]; const key = [...o.kinds].sort().join('|'); return o.kinds.length > 1 ? key + '#' + c.idx : key; };
  for (let e = 0; e < nE; e++) {
    const s = k.src[e], d = k.dst[e], sp = k.srcPort[e], dp = k.dstPort[e];
    have.add(s + ':' + d + ':' + sp + ':' + dp);
    const ck = d + ':' + dp;
    if (!claim.has(ck)) claim.set(ck, portKeyOf(brain.cells[s], sp));
    if (!live.edges.has(e)) continue;
    delivers[s] = 1; reached.add(ck);
    const dk = s + ':' + sp;
    if (!donorEdge.has(dk)) donorEdge.set(dk, e);
  }
  const donors = [...donorEdge.entries()].map(([dk, e]) => { const [s, sp] = dk.split(':').map(Number); return { s, sp, e, cell: brain.cells[s], key: portKeyOf(brain.cells[s], sp) }; });
  const readsMail = (c) => readsMailWithin(c, horizon);
  const counts = { cells: nC, silent: 0, silentCanRead: 0, protectedSkipped: 0, clockSkipped: 0, portsUnreached: 0, portsWired: 0, portsNoDonor: 0, cellsWired: 0, cellsNeverRanWired: 0, donors: donors.length, edgesBefore: nE, edgesAfter: nE };
  const wired = [];
  const wiring = new Wiring(brain, { reserve: nE + nC, strict: true });
  for (let i = 0; i < nC; i++) {
    if (delivers[i]) continue;
    counts.silent++;
    const c = brain.cells[i];
    if (prot[i]) { counts.protectedSkipped++; continue; }
    if (!readsMail(c)) { counts.clockSkipped++; continue; }
    counts.silentCanRead++;
    let any = false;
    for (let dp = 0; dp < c.ports.in.length; dp++) {
      if (reached.has(i + ':' + dp)) continue;
      counts.portsUnreached++;
      const inPort = c.ports.in[dp], owner = claim.get(i + ':' + dp);
      let best = null, bestRank = null;
      for (const d of donors) {
        if (d.s === i) continue;
        if (!d.cell.ports.out[d.sp].kinds.every((x) => inPort.kinds.includes(x))) continue;
        if (owner !== undefined && owner !== d.key) continue;
        if (have.has(d.s + ':' + i + ':' + d.sp + ':' + dp)) continue;
        const near = d.cell.circuit === c.circuit && d.cell.region === c.region ? 0 : d.cell.region === c.region ? 1 : 2;
        const rank = [near, Math.abs(d.s - i), d.s, d.sp];
        if (bestRank === null || lexLess(rank, bestRank)) { best = d; bestRank = rank; }
      }
      if (!best) { counts.portsNoDonor++; continue; }
      const e = best.e;
      const w = k.w[e], delay = k.delay[e], conf = k.conf[e];
      const id = wiring.add(best.s, i, best.sp, dp, { w, delay, conf });
      if (id < 0) throw new Error('wire: the edge ' + best.cell.id + '.' + best.sp + ' to ' + c.id + '.' + dp + ' was refused');
      have.add(best.s + ':' + i + ':' + best.sp + ':' + dp);
      claim.set(i + ':' + dp, best.key);
      counts.portsWired++; any = true;
      wired.push({ src: best.cell.id, dst: c.id, srcPort: best.sp, dstPort: dp, kind: c.kind, from: best.cell.kind, near: ['circuit', 'region', 'organism'][bestRank[0]], donorEdge: e, dstRan: live.cells.has(i) });
    }
    if (any) { counts.cellsWired++; if (!live.cells.has(i)) counts.cellsNeverRanWired++; }
  }
  wiring.finish();
  counts.edgesAfter = k.n;
  const { loaded, hash, wiring: loadWiring, ...genome } = brain.genome || {};
  // the latest round at the top (what the last wire did), every round kept in order under rounds
  const round = { from: brain.name, fromHash: hash ?? null, horizon, ...counts, ...(note ? { census: note } : {}) };
  const prior = genome.wired ? (Array.isArray(genome.wired.rounds) ? genome.wired.rounds : [(({ rounds, ...r }) => r)(genome.wired)]) : [];
  brain.genome = { ...genome, wired: { ...round, rounds: [...prior, round] } };
  return { brain, wired, counts };
}
/**
 * Load the seed a census names, refusing before any import when its manifest hash is not the one
 * the census was taken on. With checkContent (the wire always; a prune that rewrites the seed in
 * place), the loaded content is also verified against its own manifest: a seed replaced in place
 * earlier in the same process is served its old parts files from the import cache, and emitting
 * over the seed from that stale copy would land content its census never measured.
 * @param {string} who @param {string} seedDir @param {object} census @param {{ checkContent: boolean }} opts
 */
async function loadCensusSeed(who, seedDir, census, { checkContent }) {
  const { loadFrom, verify, readManifest } = await import('./load.mjs');
  const m = readManifest(seedDir);
  if (census.live.manifestHash !== m.hash) throw new Error(who + ': the census was taken on organism hash ' + census.live.manifestHash + ', ' + seedDir + ' has ' + m.hash);
  const stale = ' (a seed rewritten in place earlier in this process is served from the import cache: run each step in its own process)';
  let loaded;
  try { loaded = await loadFrom(seedDir); } catch (err) { if (!checkContent) throw err; throw new Error(who + ': ' + seedDir + ' did not load: ' + err.message + stale); }
  if (checkContent) {
    const v = verify(loaded.brain, loaded.manifest);
    if (!v.ok) throw new Error(who + ': ' + seedDir + ' loaded content its manifest does not describe: ' + v.errors[0] + stale);
  }
  return loaded;
}
function lexLess(a, b) { for (let j = 0; j < a.length; j++) if (a[j] !== b[j]) return a[j] < b[j]; return false; }

/**
 * Whether a cell reads its mail inside a census horizon: an event cell runs when mail arrives, a
 * periodic cell runs at every multiple of its period, so one whose period is past the horizon runs
 * at tick 0 only and never reads what is delivered to it after that inside the census.
 * @param {object} c a cell @param {number} horizon the census's last tick bound
 */
export function readsMailWithin(c, horizon) {
  const p = c.policy.period;
  return p === 'event' || (typeof p === 'number' && p >= 1 && p <= horizon);
}

// Two line rulers, never mixed in one print (Board 23 dead-share fix pass). THE MANIFEST COUNT is
// manifest.json's counts.lines as written to disk: every emitted file but manifest.json (the ruler
// pruneStaticMain prints and pruneOnCopy reads). THE CENSUS RULER is every file of the seed with
// manifest.json included, counted as tools/organism-census.mjs counts lines present and as the gate
// divides by (text.split('\n').length per file). emitOrganism's res.lines is the census ruler.
/** Physical lines of every file in a directory, manifest.json included (the census ruler). */
export function censusLinesOf(dir) {
  let n = 0;
  for (const f of readdirSync(dir)) { const p = path.join(dir, f); if (statSync(p).isFile()) n += readFileSync(p, 'utf8').split('\n').length; }
  return n;
}
/** The manifest count on disk: counts.lines of dir/manifest.json (every emitted file but manifest.json). */
export function manifestLinesOf(dir) {
  const m = JSON.parse(readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  if (!(m.counts && Number.isInteger(m.counts.lines))) throw new Error('lines: ' + dir + '/manifest.json carries no counts.lines');
  return m.counts.lines;
}

/**
 * The directory to emit into, and how to land it. Emitting over the seed being read (the prune or
 * the wire of a seed in place) writes a sibling staging directory at the same depth (so index.mjs
 * imports genome/load.mjs by the same relative path), reads it back from there (a module already
 * imported from the seed's own path would be served from the import cache), then replaces the seed.
 *
 * The replacement never deletes the seed before its successor is in place (Board 23 dead-share fix
 * pass: the first version removed the seed, then renamed the staging over it, so a rename refused by
 * Windows left no seed at all). The seed steps aside first (renamed to a sibling .<name>.emit-replaced,
 * nothing deleted), the staging is renamed into its place, and only then is the old seed removed. A
 * refused second rename puts the seed back and removes the staging. Windows refuses a rename with
 * EPERM, EACCES or EBUSY while another process (the search indexer, an antivirus scan) still holds a
 * file of the directory open for a moment after it was written; the same rename a moment later goes
 * through. graceful-fs (npm's fs wrapper) retries a rename on exactly those codes on win32 with a
 * growing backoff, and so does this (retrying below). fsOps replaces the fs calls, for the tests.
 * @param {string} outDir @param {string} seedDir
 * @param {{ rename?: Function, rm?: Function, exists?: Function, sleep?: Function }} [fsOps]
 */
export function emitTarget(outDir, seedDir, fsOps = {}) {
  const { rename = renameSync, rm = rmSync, exists = existsSync, sleep = sleepSync } = fsOps;
  if (!samePath(outDir, seedDir)) return { dir: outDir, inPlace: false, land: () => outDir, discard: () => {} };
  const parent = path.dirname(outDir), base = path.basename(outDir);
  const staging = path.join(parent, '.' + base + '.emit-staging');
  const replaced = path.join(parent, '.' + base + '.emit-replaced');
  const remove = (p) => rm(p, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
  const again = (fn) => retrying(fn, { sleep });
  // what a run that died half way left: a staging never landed, a replaced seed never removed (the
  // seed itself is at outDir: it was just read from there)
  if (exists(staging)) remove(staging);
  if (exists(replaced)) remove(replaced);
  return {
    dir: staging, inPlace: true, staging, replaced,
    land: () => {
      again(() => rename(outDir, replaced));
      try { again(() => rename(staging, outDir)); } catch (err) {
        try { again(() => rename(replaced, outDir)); } catch (err2) {
          throw new Error('emit: ' + staging + ' could not take the place of ' + outDir + ' (' + err.code + '), and the seed could not be put back (' + err2.code + '): the seed is intact at ' + replaced);
        }
        remove(staging);
        throw new Error('emit: ' + staging + ' could not take the place of ' + outDir + ' (' + (err.code || err.message) + '); the seed is left as it was');
      }
      remove(replaced);
      return outDir;
    },
    discard: () => remove(staging),
  };
}

// The codes Windows answers a rename with while another process holds a file of the directory open,
// and the retry graceful-fs gives them: a growing wait, capped, then the error is thrown after all.
const TRANSIENT_RENAME = new Set(['EPERM', 'EACCES', 'EBUSY']);
/**
 * Call fn, again after a growing wait while it throws a transient rename error.
 * @param {() => any} fn @param {{ tries?: number, firstMs?: number, maxMs?: number, sleep?: (ms:number)=>void }} [opts]
 */
export function retrying(fn, { tries = 12, firstMs = 20, maxMs = 1000, sleep = sleepSync } = {}) {
  let wait = firstMs;
  for (let t = 1; ; t++) {
    try { return fn(); } catch (err) {
      if (t >= tries || !TRANSIENT_RENAME.has(err && err.code)) throw err;
      sleep(wait);
      wait = Math.min(maxMs, wait * 2);
    }
  }
}
function sleepSync(ms) { Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms); }

/**
 * The declarations of each emitted file, as index ranges in load order: cells files in the
 * order the manifest lists them give cells 0, 1, ...; edges files likewise give edges. This is
 * the same line order loadOrganism replays.
 * @param {string} dir @param {object} manifest
 * @returns {Map<string, { kind: 'cells'|'edges', start: number, count: number }>}
 */
export function declarationRanges(dir, manifest) {
  const out = new Map();
  let nc = 0, ne = 0;
  for (const f of manifest.files || []) {
    const kind = /^cells-/.test(f.path) ? 'cells' : /^edges-/.test(f.path) ? 'edges' : null;
    if (!kind) continue;
    const pre = kind === 'cells' ? 'c(' : 'e(';
    let count = 0;
    for (const line of readFileSync(path.join(dir, f.path), 'utf8').split('\n')) if (line.startsWith(pre)) count++;
    out.set(f.path, { kind, start: kind === 'cells' ? nc : ne, count });
    if (kind === 'cells') nc += count; else ne += count;
  }
  return out;
}

/**
 * What a census verdict protects from pruning beyond its liveness: the cells its hosted
 * problems ran on, and every declaration of a file whose knockout lowered a hosted score.
 * @param {object} census a census verdict
 * @param {object} brain the loaded seed @param {string} dir @param {object} manifest
 * @returns {{ cells: number[], edges: number[], why: string[] }}
 */
export function protectedByCensus(census, brain, dir, manifest) {
  const cells = new Set(), edges = new Set(), why = [];
  const idxOf = new Map(brain.cells.map((c, i) => [c.id, i]));
  const hosted = [];
  for (const suite of ['algebra', 'sequence']) for (const id of (census.tasks && census.tasks[suite] && census.tasks[suite].cells) || []) hosted.push(id);
  for (const id of hosted) { const i = idxOf.get(id); if (i === undefined) throw new Error('prune: the census hosted a problem on ' + id + ', which the seed does not declare'); cells.add(i); }
  if (hosted.length) why.push(hosted.length + ' cells the hosted problems ran on (' + hosted.join(', ') + ')');
  let ranges = null;
  for (const ko of census.knockouts || []) {
    const d = ko.delta || {};
    const lowered = (d.taskScore || 0) < 0 || (d.algebraCorrect || 0) < 0 || (d.sequenceCorrect || 0) < 0;
    if (!lowered) { why.push('knockout of ' + ko.file + ' (' + ko.role + ') lowered no hosted score (task score delta ' + (d.taskScore || 0) + '), so it protects nothing beyond what ran or delivered'); continue; }
    ranges = ranges || declarationRanges(dir, manifest);
    const r = ranges.get(ko.file);
    if (!r) throw new Error('prune: knockout file ' + ko.file + ' is not in the manifest');
    for (let j = r.start; j < r.start + r.count; j++) (r.kind === 'cells' ? cells : edges).add(j);
    why.push('knockout of ' + ko.file + ' (' + ko.role + ') lowered a hosted score (task score delta ' + d.taskScore + '), so all ' + r.count + ' of its ' + r.kind + ' are kept');
  }
  return { cells: [...cells], edges: [...edges], why };
}

// ---------------------------------------------------------------- CLI
//   node genome/emit.mjs --prune bench/verdicts/census.json [--seed organism/gen-0]
//                        [--out dir] [--name gen-0-pruned]
// Loads the seed the census was taken on (refusing one whose manifest hash differs), writes
// the pruned copy (default bench/verdicts/.census/<name>, a dot directory the gate does not
// count as generated lines), then loads the pruned copy back and verifies it.
export async function pruneMain(argv) {
  const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
  const censusFile = path.resolve(opt('prune', ''));
  if (!existsSync(censusFile)) throw new Error('prune: no census file at ' + censusFile);
  const census = JSON.parse(readFileSync(censusFile, 'utf8'));
  // a static census (tools/organism-census.mjs --static) never loaded the seed, and the prune by it
  // does not either: pruneStatic streams the seed line by line (below)
  if (census.mode === 'static') return pruneStaticMain(argv, census, censusFile);
  if (!census.live || !census.live.cells || !census.live.edges) throw new Error('prune: ' + censusFile + ' carries no liveness (a census written by tools/organism-census.mjs does)');
  const seedDir = path.resolve(BRAIN_ROOT, opt('seed', census.seed));
  const name = opt('name', path.basename(seedDir) + '-pruned');
  const outDir = path.resolve(opt('out', path.join(BRAIN_ROOT, 'bench', 'verdicts', '.census', name)));
  const say = argv.includes('--quiet') ? () => {} : (s) => process.stdout.write(s + '\n');
  await import('../cells/all.mjs');
  const { loadFrom, verify } = await import('./load.mjs');
  const t0 = Date.now();
  const { brain, manifest } = await loadCensusSeed('prune', seedDir, census, { checkContent: samePath(outDir, seedDir) });
  // the seed's census ruler is read now: a prune in place replaces the directory before the print
  const censusBefore = censusLinesOf(seedDir);
  applyWireHistory(brain, argv, seedDir, say);
  const cells = readLiveBits(census.live.cells), edges = readLiveBits(census.live.edges);
  const inFlight = census.live.inFlight ? readLiveBits(census.live.inFlight) : null;
  const protect = protectedByCensus(census, brain, seedDir, manifest);
  const { brain: pruned, dropped, kept } = pruneBrain(brain, { cells, edges, inFlight }, { name, protect, note: { file: toPosix(path.relative(BRAIN_ROOT, censusFile)), at: census.at, ticks: census.ticks, phases: census.live.phases } });
  const target = emitTarget(outDir, seedDir);
  const res = emitOrganism(pruned, { dir: target.dir });
  const back = await loadFrom(target.dir);
  const v = verify(back.brain, back.manifest);
  const wantCells = pruned.cells.length, wantEdges = pruned.connectome.n;
  // the invariant, checked on the reloaded copy: every cell that ran and every edge that
  // delivered is still declared, by id and by its two endpoints and ports
  const backIdx = new Map(back.brain.cells.map((c, i) => [c.id, i]));
  let lostCells = 0, lostEdges = 0;
  for (let i = 0; i < brain.cells.length; i++) if (cells.has(i) && !backIdx.has(brain.cells[i].id)) lostCells++;
  const bk = back.brain.connectome, sk = brain.connectome, have = new Set();
  for (let e = 0; e < bk.n; e++) have.add(back.brain.cells[bk.src[e]].id + '>' + back.brain.cells[bk.dst[e]].id + ':' + bk.srcPort[e] + ':' + bk.dstPort[e]);
  for (let e = 0; e < sk.n; e++) if ((edges.has(e) || (inFlight && inFlight.has(e))) && !have.has(brain.cells[sk.src[e]].id + '>' + brain.cells[sk.dst[e]].id + ':' + sk.srcPort[e] + ':' + sk.dstPort[e])) lostEdges++;
  // one ruler per print: before and after both the manifest count (the manifest.json on disk, which
  // leaves out its own lines), and both the census ruler (every file, manifest.json included);
  // res.lines is the census ruler of the copy, so it is never set against the seed's manifest count
  const linesBefore = manifest.counts && manifest.counts.lines;
  const linesAfter = back.manifest.counts && back.manifest.counts.lines;
  const lines = { before: linesBefore, after: linesAfter, removed: linesBefore - linesAfter, ruler: 'manifest count: every emitted file but manifest.json', census: { before: censusBefore, after: res.lines, removed: censusBefore - res.lines, ruler: 'every file of the seed, manifest.json included (tools/organism-census.mjs lines present)' } };
  // what the census calls delivered but no cell reads inside its horizon: a kept edge into a cell
  // whose period is past the horizon (it runs at tick 0 only). Kept by the rule (it delivered), and
  // counted, because such an edge is load bearing by the census's rule and not shown read by it.
  const horizon = census.dormant && census.dormant.lastTickBound;
  let unread = null;
  if (Number.isInteger(horizon)) {
    const pk = pruned.connectome, into = new Set();
    let n = 0;
    for (let e = 0; e < pk.n; e++) if (!readsMailWithin(pruned.cells[pk.dst[e]], horizon)) { n++; into.add(pk.dst[e]); }
    let slow = 0;
    for (const c of pruned.cells) if (!readsMailWithin(c, horizon)) slow++;
    unread = { horizon, keptEdges: pk.n, edges: n, cells: into.size, cellsNoRunAfterTick0: slow };
  }
  const ok = v.ok && back.brain.cells.length === wantCells && bk.n === wantEdges && lostCells === 0 && lostEdges === 0;
  // in place, the seed is replaced only by a copy that round tripped; otherwise the staging goes
  if (ok) res.dir = target.land(); else target.discard();
  say('prune ' + toPosix(path.relative(BRAIN_ROOT, seedDir)) + ' by ' + toPosix(path.relative(BRAIN_ROOT, censusFile)) + ' (census at ' + census.at + ', ' + census.ticks + ' ticks)');
  say('  lines ' + lines.before + ' -> ' + lines.after + ' (manifest count: every emitted file but manifest.json): ' + lines.removed + ' removed, ' + (100 * lines.removed / lines.before).toFixed(2) + '% of the seed');
  say('  lines ' + lines.census.before + ' -> ' + lines.census.after + ' (census ruler: every file, manifest.json included): ' + lines.census.removed + ' removed');
  say('  cells ' + brain.cells.length + ' -> ' + pruned.cells.length + ': kept ' + kept.cells.ran + ' that ran, ' + kept.cells.protectedOnly + ' protected that never ran, ' + kept.cells.endpointOnly + ' that never ran but are an endpoint of a kept edge; dropped ' + dropped.cells);
  say('  edges ' + brain.connectome.n + ' -> ' + pruned.connectome.n + ': kept ' + kept.edges.delivered + ' that delivered, ' + kept.edges.inFlightOnly + ' in flight at the end' + (kept.edges.inFlightRecorded ? '' : ' (this census recorded no in flight set)') + ', ' + kept.edges.protectedOnly + ' protected; dropped ' + dropped.edgesNeverDelivered + ' that never delivered');
  for (const w of protect.why) say('  protect    ' + w);
  if (unread) say('  unread     ' + unread.edges + ' of ' + unread.keptEdges + ' kept edges deliver into ' + unread.cells + ' cells with no run after tick 0 inside horizon tick ' + unread.horizon + ' (' + unread.cellsNoRunAfterTick0 + ' kept cells are on such a clock): the census counts them delivered; no cell reads that mail inside the census');
  say('  regions dropped ' + dropped.regions + ', circuits dropped ' + dropped.circuits);
  say('  emitted ' + toPosix(path.relative(BRAIN_ROOT, res.dir)) + ': ' + (res.files.length + 1) + ' files, ' + lines.after + ' lines by the manifest count, ' + lines.census.after + ' on the census ruler, ' + res.bytes + ' bytes before the manifest');
  say('  round trip: loaded ' + back.brain.cells.length + ' cells and ' + bk.n + ' edges (expected ' + wantCells + ' and ' + wantEdges + '), verify ' + (v.ok ? 'ok' : 'FAILED: ' + v.errors.join('; ')) + ', hash ' + v.hash.slice(0, 16) + '; of what ran or delivered, ' + lostCells + ' cells and ' + lostEdges + ' edges are missing from the copy');
  say('  ' + (ok ? 'ROUND TRIP OK' : 'ROUND TRIP FAILED') + ' in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  return { ok, dir: res.dir, dropped, kept, protect, lines, unread, cells: back.brain.cells.length, edges: bk.n, expected: { cells: wantCells, edges: wantEdges }, lost: { cells: lostCells, edges: lostEdges }, verify: v };
}

//   node genome/emit.mjs --wire bench/verdicts/census-<seed>.json [--seed organism/<seed>]
//                        [--out dir] [--name <seed>]
// Loads the seed the census was taken on (refusing one whose manifest hash differs), wires every
// silent cell's unreached in ports from ports that delivered (wireBrain above), writes the wired
// seed (default bench/verdicts/.census/<name>-wired; --out equal to --seed rewrites the seed in
// place, through emitTarget), loads it back, verifies it, and checks that every original cell and
// every original edge is still declared, in the original order, ahead of the wired ones. The wired
// seed is then censused, and --prune by that census removes what still never runs.
export async function wireMain(argv) {
  const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
  const censusFile = path.resolve(opt('wire', ''));
  if (!existsSync(censusFile)) throw new Error('wire: no census file at ' + censusFile);
  const census = JSON.parse(readFileSync(censusFile, 'utf8'));
  if (census.mode === 'static') throw new Error('wire: ' + censusFile + ' is a static census; wiring reads what delivered, which only a dynamic census measures');
  if (!census.live || !census.live.cells || !census.live.edges) throw new Error('wire: ' + censusFile + ' carries no liveness (a census written by tools/organism-census.mjs does)');
  const horizon = census.dormant && census.dormant.lastTickBound;
  if (!Number.isInteger(horizon)) throw new Error('wire: ' + censusFile + ' records no horizon (dormant.lastTickBound)');
  const seedDir = path.resolve(BRAIN_ROOT, opt('seed', census.seed));
  const name = opt('name', path.basename(seedDir));
  const outDir = path.resolve(opt('out', path.join(BRAIN_ROOT, 'bench', 'verdicts', '.census', name + '-wired')));
  const say = argv.includes('--quiet') ? () => {} : (s) => process.stdout.write(s + '\n');
  await import('../cells/all.mjs');
  const { loadFrom, verify } = await import('./load.mjs');
  const t0 = Date.now();
  const { brain, manifest } = await loadCensusSeed('wire', seedDir, census, { checkContent: true });
  const censusBefore = censusLinesOf(seedDir);
  const historyAdded = applyWireHistory(brain, argv, seedDir, say);
  const cells = readLiveBits(census.live.cells), edges = readLiveBits(census.live.edges);
  const idxOf = new Map(brain.cells.map((c, i) => [c.id, i]));
  const hosted = [];
  for (const suite of ['algebra', 'sequence']) for (const id of (census.tasks && census.tasks[suite] && census.tasks[suite].cells) || []) {
    const i = idxOf.get(id);
    if (i === undefined) throw new Error('wire: the census hosted a problem on ' + id + ', which the seed does not declare');
    hosted.push(i);
  }
  const k0 = brain.connectome, nC0 = brain.cells.length, nE0 = k0.n;
  const before = [];
  for (let e = 0; e < nE0; e++) before.push(brain.cells[k0.src[e]].id + '>' + brain.cells[k0.dst[e]].id + ':' + k0.srcPort[e] + ':' + k0.dstPort[e]);
  brain.name = name;
  const { wired, counts } = wireBrain(brain, { cells, edges }, { horizon, protect: hosted, note: { file: toPosix(path.relative(BRAIN_ROOT, censusFile)), at: census.at, ticks: census.ticks, phases: census.live.phases } });
  const head = () => {
    say('wire ' + toPosix(path.relative(BRAIN_ROOT, seedDir)) + ' by ' + toPosix(path.relative(BRAIN_ROOT, censusFile)) + ' (census at ' + census.at + ', ' + census.ticks + ' ticks, horizon tick ' + horizon + ')');
    say('  cells ' + counts.cells + ': silent (no out edge delivered) ' + counts.silent + ', of which hosted (never wired) ' + counts.protectedSkipped + ', on a clock with no run after tick 0 inside the horizon ' + counts.clockSkipped + ', can read mail ' + counts.silentCanRead);
    say('  in ports no delivered edge reached, on those cells: ' + counts.portsUnreached + '; wired ' + counts.portsWired + ' from ' + counts.donors + ' ports that delivered; no legal donor ' + counts.portsNoDonor);
    say('  cells wired ' + counts.cellsWired + ' (' + counts.cellsNeverRanWired + ' of them never ran); edges ' + counts.edgesBefore + ' -> ' + counts.edgesAfter);
  };
  // a round that wires nothing over the seed itself is the fixed point: the seed is left as it is
  // (rewriting it would only add a round that wired nothing to its record), unless rebuilt wire
  // history was added (--wire-history): then the seed is written again, the same cells and edges
  // under a record that now holds the rounds it had lost
  if (wired.length === 0 && samePath(outDir, seedDir) && historyAdded === 0) {
    head();
    say('  nothing to wire: the fixed point; ' + toPosix(path.relative(BRAIN_ROOT, seedDir)) + ' is left as it is');
    const same = manifest.counts && manifest.counts.lines;
    return { ok: true, unchanged: true, dir: seedDir, counts, wired, lines: { before: same, after: same, removed: 0, ruler: 'manifest count: every emitted file but manifest.json', census: { before: censusBefore, after: censusBefore, removed: 0, ruler: 'every file of the seed, manifest.json included (tools/organism-census.mjs lines present)' } }, cells: nC0, edges: nE0, moved: 0, verify: verify(brain, manifest) };
  }
  const target = emitTarget(outDir, seedDir);
  const res = emitOrganism(brain, { dir: target.dir });
  const back = await loadFrom(target.dir);
  const v = verify(back.brain, back.manifest);
  const bk = back.brain.connectome;
  let moved = 0;
  for (let e = 0; e < nE0; e++) if (e >= bk.n || back.brain.cells[bk.src[e]].id + '>' + back.brain.cells[bk.dst[e]].id + ':' + bk.srcPort[e] + ':' + bk.dstPort[e] !== before[e]) moved++;
  const cellsSame = back.brain.cells.length === nC0;
  const ok = v.ok && cellsSame && moved === 0 && bk.n === nE0 + wired.length;
  // the same two rulers as the prune, never mixed: back.manifest is the manifest on disk (its count
  // leaves out manifest.json), res.lines is every file with manifest.json
  const before0 = manifest.counts && manifest.counts.lines, after0 = back.manifest.counts && back.manifest.counts.lines;
  const lines = { before: before0, after: after0, removed: before0 - after0, ruler: 'manifest count: every emitted file but manifest.json', census: { before: censusBefore, after: res.lines, removed: censusBefore - res.lines, ruler: 'every file of the seed, manifest.json included (tools/organism-census.mjs lines present)' } };
  if (ok) res.dir = target.land(); else target.discard();
  head();
  for (const w of wired) say('  wired      ' + w.from + ' ' + w.src + '.' + w.srcPort + ' -> ' + w.kind + ' ' + w.dst + '.' + w.dstPort + ' (' + w.near + (w.dstRan ? '' : ', the cell never ran') + ')');
  say('  lines ' + lines.before + ' -> ' + lines.after + ' (manifest count: every emitted file but manifest.json); ' + lines.census.before + ' -> ' + lines.census.after + ' (census ruler: every file, manifest.json included)');
  say('  emitted ' + toPosix(path.relative(BRAIN_ROOT, res.dir)) + ': ' + (res.files.length + 1) + ' files, ' + lines.after + ' lines by the manifest count, ' + lines.census.after + ' on the census ruler, ' + res.bytes + ' bytes before the manifest');
  say('  round trip: loaded ' + back.brain.cells.length + ' cells and ' + bk.n + ' edges (expected ' + nC0 + ' and ' + (nE0 + wired.length) + '), verify ' + (v.ok ? 'ok' : 'FAILED: ' + v.errors.join('; ')) + ', hash ' + v.hash.slice(0, 16) + '; original edges out of place ' + moved);
  say('  ' + (ok ? 'ROUND TRIP OK' : 'ROUND TRIP FAILED') + ' in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  return { ok, dir: res.dir, counts, wired, lines, cells: back.brain.cells.length, edges: bk.n, moved, verify: v };
}


// ---------------------------------------------------------------- wire history (Board 23 dead-share fix pass)
//
// organism/gen-1-4-4-1-4 was wired twice (72 edges, then 30) before the round that wired nothing,
// and its manifest kept only that last round: wireBrain then replaced the record of the round before
// it instead of appending (it appends now, under wired.rounds). The two rounds are rebuilt here from
// the census verdicts taken between them, which are committed: each census records the manifest hash
// of the seed it measured (live.manifestHash) and its declared cells and edges, so consecutive
// censuses of one seed give each round's hash link (from, to), its edge counts before and after, and
// the edges it wired (a wire appends only: the seed's first n edges are the original n). The census
// the recorded prune read gives, from its liveness, how many of each round's edges delivered there
// and so were kept. What only a wire run prints (silent cells, clock skipped, ports unreached, ports
// with no donor, cells wired) was never written anywhere and is recorded as not recovered.

/**
 * Rebuild wire rounds from the census verdicts taken before and after each of them.
 * @param {Array<{ file: string, v: object }>} censuses in the order they were taken; each after the
 *   first measured the seed the wire round by the one before it wrote
 * @param {{ seed?: string, pruned?: object }} [opts] seed: the seed path every census must name;
 *   pruned: the recorded prune record, whose census gives how many wired edges were kept
 * @returns {object[]} one round per consecutive pair
 */
export function wireHistory(censuses, { seed = null, pruned = null } = {}) {
  if (!Array.isArray(censuses) || censuses.length < 2) throw new Error('wire history: need at least two census verdicts, got ' + (censuses ? censuses.length : 0));
  for (const { file, v } of censuses) {
    if (!v || !v.live || typeof v.live.manifestHash !== 'string') throw new Error('wire history: ' + file + ' records no manifest hash (live.manifestHash)');
    if (!v.cells || !Number.isInteger(v.cells.declared) || !v.edges || !Number.isInteger(v.edges.declared)) throw new Error('wire history: ' + file + ' records no declared cells and edges');
    if (seed !== null && v.seed !== seed) throw new Error('wire history: ' + file + ' is a census of ' + v.seed + ', not ' + seed);
  }
  const last = censuses[censuses.length - 1];
  const kept = pruned && pruned.census && pruned.census.file && toPosix(pruned.census.file) === toPosix(last.file) && pruned.fromHash === last.v.live.manifestHash
    ? { edges: readLiveBits(last.v.live.edges), inFlight: last.v.live.inFlight ? readLiveBits(last.v.live.inFlight) : null } : null;
  const rounds = [];
  for (let i = 0; i + 1 < censuses.length; i++) {
    const a = censuses[i], b = censuses[i + 1];
    if (a.v.live.manifestHash === b.v.live.manifestHash) throw new Error('wire history: ' + a.file + ' and ' + b.file + ' measured the same seed (hash ' + a.v.live.manifestHash.slice(0, 16) + '): no wire round lies between them');
    if (!(Date.parse(b.v.at) > Date.parse(a.v.at))) throw new Error('wire history: ' + b.file + ' was not taken after ' + a.file);
    if (b.v.cells.declared !== a.v.cells.declared) throw new Error('wire history: the cells went ' + a.v.cells.declared + ' -> ' + b.v.cells.declared + ' between ' + a.file + ' and ' + b.file + '; a wire round adds edges only');
    if (!(b.v.edges.declared > a.v.edges.declared)) throw new Error('wire history: the edges went ' + a.v.edges.declared + ' -> ' + b.v.edges.declared + ' between ' + a.file + ' and ' + b.file + '; a wire round that wrote a new seed added edges');
    const horizon = a.v.dormant && a.v.dormant.lastTickBound;
    if (!Number.isInteger(horizon)) throw new Error('wire history: ' + a.file + ' records no horizon (dormant.lastTickBound)');
    let deliveredAtPrune = null, inFlightAtPrune = null;
    if (kept) {
      deliveredAtPrune = 0; inFlightAtPrune = 0;
      for (let e = a.v.edges.declared; e < b.v.edges.declared; e++) {
        if (kept.edges.has(e)) deliveredAtPrune++;
        else if (kept.inFlight && kept.inFlight.has(e)) inFlightAtPrune++;
      }
    }
    rounds.push({
      from: path.basename(a.v.seed), fromHash: a.v.live.manifestHash, toHash: b.v.live.manifestHash, horizon,
      cells: a.v.cells.declared, edgesBefore: a.v.edges.declared, edgesAfter: b.v.edges.declared, portsWired: b.v.edges.declared - a.v.edges.declared,
      ...(kept ? { keptByPrune: { census: toPosix(last.file), delivered: deliveredAtPrune, inFlightOnly: inFlightAtPrune } } : {}),
      census: { file: toPosix(a.file), at: a.v.at, ticks: a.v.ticks, phases: a.v.live.phases },
      after: { file: toPosix(b.file), at: b.v.at },
      reconstructed: 'rebuilt from the census verdicts before and after the round (genome/emit.mjs wireHistory): the hashes, the edge counts and the edges wired are theirs; what only the wire run printed (silent cells, clock skipped, ports unreached, ports with no donor, cells wired) was not recorded and is not recovered',
      notRecovered: ['silent', 'silentCanRead', 'protectedSkipped', 'clockSkipped', 'portsUnreached', 'portsNoDonor', 'cellsWired', 'cellsNeverRanWired', 'donors'],
    });
  }
  return rounds;
}

/**
 * Put rebuilt rounds ahead of a genome's recorded wire rounds, once. A round is known by the hash of
 * the seed it wired (a wire is a function of the seed and of the census of it, and the census of one
 * seed is the same census), so a rebuilt round whose seed a recorded round already wired is not added
 * and a second landing changes nothing. What is added must end where the recorded rounds start.
 * @param {object} genome a brain's genome record @param {object[]} rebuilt from wireHistory
 * @returns {{ genome: object, added: number }}
 */
export function mergeWireHistory(genome, rebuilt) {
  const w = genome && genome.wired;
  const recorded = w ? (Array.isArray(w.rounds) ? w.rounds : [(({ rounds, ...r }) => r)(w)]) : [];
  const have = new Set(recorded.map((r) => r.fromHash));
  const fresh = rebuilt.filter((r) => !have.has(r.fromHash));
  if (!fresh.length) return { genome, added: 0 };
  const end = fresh[fresh.length - 1].toHash;
  const firstRecorded = recorded.find((r) => !r.reconstructed && !have.has(r.toHash));
  if (firstRecorded && firstRecorded.fromHash !== end) throw new Error('wire history: the rebuilt rounds end at ' + String(end).slice(0, 16) + ', the first recorded round starts from ' + String(firstRecorded.fromHash).slice(0, 16));
  const rounds = [...recorded.filter((r) => r.reconstructed), ...fresh, ...recorded.filter((r) => !r.reconstructed)];
  const top = w ? (({ rounds: _r, ...r }) => r)(w) : rounds[rounds.length - 1];
  return { genome: { ...genome, wired: { ...top, rounds } }, added: fresh.length };
}

/** --wire-history a.json,b.json,...: rebuild the rounds between those censuses into the brain's genome. */
function applyWireHistory(brain, argv, seedDir, say) {
  const i = argv.indexOf('--wire-history');
  if (i < 0) return 0;
  const list = String(argv[i + 1] || '').split(',').filter(Boolean);
  const censuses = list.map((f) => { const abs = path.resolve(BRAIN_ROOT, f); if (!existsSync(abs)) throw new Error('wire history: no census file at ' + abs); return { file: toPosix(path.relative(BRAIN_ROOT, abs)), v: JSON.parse(readFileSync(abs, 'utf8')) }; });
  const g = brain.genome || {};
  const rebuilt = wireHistory(censuses, { seed: toPosix(path.relative(BRAIN_ROOT, seedDir)), pruned: g.pruned || null });
  const recordedN = g.wired ? (Array.isArray(g.wired.rounds) ? g.wired.rounds.length : 1) : 0;
  const { genome, added } = mergeWireHistory(g, rebuilt);
  brain.genome = genome;
  for (const r of rebuilt) say('  history    wire round ' + r.fromHash.slice(0, 16) + ' -> ' + r.toHash.slice(0, 16) + ': edges ' + r.edgesBefore + ' -> ' + r.edgesAfter + ' (' + r.portsWired + ' wired' + (r.keptByPrune ? ', ' + r.keptByPrune.delivered + ' of them delivered in the census the prune read and were kept' : '') + '), rebuilt from ' + r.census.file + ' and ' + r.after.file);
  say('  history    ' + added + ' rebuilt round' + (added === 1 ? '' : 's') + ' added ahead of the ' + recordedN + ' recorded');
  return added;
}

// ---------------------------------------------------------------- the dead-share chain (Board 23 fix pass)
//   node genome/emit.mjs --dead-share organism/<seed> [--ticks 200] [--tag dead-share]
//                        [--verdict-dir bench/verdicts] [--max-rounds 8] [--wire-history a.json,b.json]
//                        [--max-passes 4] [--keep-in-flight] [--json <file>]
//   node genome/emit.mjs --dead-share --all [--max-cells 1000] [--skip a,b] [same options]
// The whole rule as one command, so a seed is never left half done and a seed emitted again is fixed
// the same way: census it; wire it in place by that census and census it again, until a round wires
// nothing (the fixed point); prune it in place by the last census; census the pruned seed. Each step
// is its own process (a seed rewritten in place is served from the import cache in the process that
// read it); each census is written to the verdict dir as census-<seed>-<tag>-c<i>-partial.json and
// checked against the seed's manifest hash; each round is recorded in the seed's manifest
// (genome.wired.rounds, genome.pruned.rounds).
//
// THE HORIZON STEP (Board 27 dead-share-all). On 12 of the 18 seeds board 23 held out, the chain
// stopped above 0 (0.000918 to 0.007389), and every dead line left was an edge the prune keeps
// because a signal was still in flight on it when the census ended: its source fires only in the last
// hosted problems and the edge's delay lands the signal after the census's last tick, so inside the
// census it never delivers (one seed also kept one event cell only as the end of such an edge). A 13th,
// organism/gen-0-5-4-2-4, kept one cell no census saw run: the hosted problems chose it for a role
// (tasks/host.mjs nameCells), no problem of the census used that role, and the prune protects every
// cell the problems chose. When the last census still has a dead share above 0 and in flight edges
// or chosen cells that never ran, the chain writes that census again with both withheld
// (census-<seed>-<tag>-c<i>-horizon-partial.json, `derived` naming the file it came from), prunes the
// seed by it, and censuses the result. The step lands only
// if nothing measured inside the horizon moved: the drive's and the whole run's runs, signals and
// deliveries, the cells that ran and fired, the edges that delivered, the mail dropped, the hosted
// score, algebra and sequence, and the roles each suite found no cell for, must all equal the census
// before it; otherwise the seed is put back from a copy taken before the step and the chain is not
// OK. What the step gives up is named: the mail those edges would deliver after the census's last
// tick, and each chosen cell it dropped. --keep-in-flight turns it off.
//
// THE PASSES. A prune also drops the edges that held a monomorphic claim on an in port (genome/wire.mjs),
// so a seed that was at the wire's fixed point before a prune may have a legal donor after it. The
// chain therefore repeats wire, prune and horizon until a pass changes nothing (--max-passes, default
// 4): a landed seed is the chain's own fixed point, and a second run over it changes nothing.

const EMITTER = fileURLToPath(import.meta.url);
function childEnv() {
  const env = {};
  for (const [k, v] of Object.entries(process.env)) if (!k.startsWith('NODE_TEST') && k !== 'NODE_OPTIONS') env[k] = v;
  return env;
}
/** The numbers of one census verdict the chain compares: the dead share on the gate's ruler, and the work. */
export function censusRow(v, file) {
  const l = v.lines || {};
  return {
    file: toPosix(path.relative(BRAIN_ROOT, file)), hash: v.live && v.live.manifestHash, at: v.at, ticks: v.ticks,
    lines: l.loaded, loadBearing: l.loadBearing, deadShare: l.loaded > 0 ? Math.round((1 - l.loadBearing / l.loaded) * 1e6) / 1e6 : null,
    cells: { declared: v.cells.declared, ran: v.cells.ran, fired: v.cells.fired }, edges: { declared: v.edges.declared, delivered: v.edges.delivered },
    score: v.tasks ? v.tasks.score : null, algebra: v.tasks ? v.tasks.algebra.correct : null, sequence: v.tasks ? v.tasks.sequence.correct : null,
    drive: v.totals ? { runs: v.totals.drive.runs, signals: v.totals.drive.signals, delivered: v.totals.drive.delivered } : null,
    dormant: v.dormant ? { lastTickBound: v.dormant.lastTickBound, cells: v.dormant.cells, mailDropped: v.dormant.mailDropped } : null,
  };
}

/**
 * What a census measured inside its horizon, the numbers the horizon step must leave unchanged: the
 * work of the drive and of the whole run (hosted problems included), what ran, fired and delivered,
 * the mail dropped, and the hosted answers. Declared counts and lines are not in it: they are what
 * the step changes.
 * @param {object} v a census verdict
 * @returns {Array<[string, number|null]>}
 */
export function horizonWork(v) {
  const t = v.totals || {}, d = t.drive || {}, a = t.all || {}, k = v.tasks || null;
  return [
    ['drive runs', d.runs], ['drive signals', d.signals], ['drive delivered', d.delivered],
    ['run runs', a.runs], ['run signals', a.signals], ['run delivered', a.delivered],
    ['cells ran', v.cells && v.cells.ran], ['cells fired', v.cells && v.cells.fired], ['edges delivered', v.edges && v.edges.delivered],
    ['mail dropped', v.dormant ? v.dormant.mailDropped : null],
    ['hosted score', k ? k.score : null], ['algebra correct', k ? k.algebra.correct : null], ['sequence correct', k ? k.sequence.correct : null],
    ['algebra roles with no cell', k && Array.isArray(k.algebra.missingRoles) ? k.algebra.missingRoles.join('|') : null],
    ['sequence roles with no cell', k && Array.isArray(k.sequence.missingRoles) ? k.sequence.missingRoles.join('|') : null],
  ].map(([n, x]) => [n, x === undefined ? null : x]);
}
/** The names of the numbers of horizonWork that differ between two censuses (a number missing on either side differs). */
export function horizonMoved(before, after) {
  const a = horizonWork(before), b = new Map(horizonWork(after));
  return a.filter(([n, x]) => x === null || b.get(n) === null || b.get(n) !== x).map(([n, x]) => n + ' ' + x + ' -> ' + b.get(n));
}
/**
 * The cell ids of an emitted seed in load order (index i is cell i), read from its cells files as text:
 * nothing is imported, so a seed rewritten in place is read as it is on disk.
 * @param {string} dir @returns {string[]}
 */
export function seedCellIds(dir) {
  const m = JSON.parse(readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  const ids = [];
  for (const f of m.files || []) {
    if (!/^cells-/.test(f.path)) continue;
    for (const line of readFileSync(path.join(dir, f.path), 'utf8').split('\n')) if (line.startsWith('c(')) ids.push(declArgs(line, 'c(')[0]);
  }
  return ids;
}
/**
 * The cells the hosted problems chose (census.tasks.<suite>.cells) that never ran in that census.
 * @param {object} v a census verdict @param {string[]} ids the seed's cell ids by index
 * @returns {string[]}
 */
export function hostedNeverRan(v, ids) {
  if (!v.live || !v.live.cells) return [];
  const ran = readLiveBits(v.live.cells);
  if (ran.n !== ids.length) throw new Error('horizon: the census covers ' + ran.n + ' cells, the seed declares ' + ids.length);
  const idx = new Map(ids.map((id, i) => [id, i]));
  const out = [];
  for (const suite of ['algebra', 'sequence']) for (const id of (v.tasks && v.tasks[suite] && v.tasks[suite].cells) || []) {
    const i = idx.get(id);
    if (i === undefined) throw new Error('horizon: the census hosted a problem on ' + id + ', which the seed does not declare');
    if (!ran.has(i) && !out.includes(id)) out.push(id);
  }
  return out;
}
/**
 * The census the horizon prune reads: the census as it was written, with two things withheld. Its in
 * flight set, so the prune keeps an edge only when it delivered (or is protected) and drops one whose
 * signal was still in flight at the census's last tick. And, from the cells the hosted problems chose,
 * the ones that never ran (the prune protects every chosen cell), so the prune drops a chosen cell no
 * problem of the census used.
 * @param {object} v a census verdict @param {string} from its file, as recorded
 * @param {string[]} [never] hostedNeverRan(v, ids)
 */
export function withheldAtHorizon(v, from, never = []) {
  if (!v.live) throw new Error('horizon: ' + from + ' carries no liveness');
  const { inFlight = null, ...live } = v.live;
  const drop = new Set(never);
  const tasks = v.tasks ? Object.fromEntries(Object.entries(v.tasks).map(([k, x]) => [k, x && typeof x === 'object' && Array.isArray(x.cells) ? { ...x, cells: x.cells.filter((id) => !drop.has(id)) } : x])) : v.tasks;
  return {
    ...v, isTheBar: false, live, tasks,
    derived: {
      from, withheld: { inFlight: inFlight ? inFlight.count : 0, of: inFlight ? inFlight.n : null, hostedNeverRan: [...drop] },
      rule: 'the census ' + from + ' with two things withheld: its in flight set (an edge kept only because a signal was still in flight on it when that census ended delivered nothing inside the census) and, from the cells its hosted problems chose, the ones that never ran in it; the prune that reads this file keeps neither',
      by: 'genome/emit.mjs deadShareChain, the horizon step (Board 27 dead-share-all)',
    },
  };
}

/**
 * Wire a seed to its fixed point and prune it, in place, each step a child process; then, when in
 * flight edges are all that is left dead, the horizon step; repeated until a pass changes nothing.
 * @param {string} seedDir
 * @param {{ ticks?, tag?, verdictDir?, maxRounds?, maxPasses?, horizon?: boolean, wireHistory?: string[], heapMb?, say?, timeoutMs? }} [opts]
 * @returns {{ seed, ticks, first, last, rounds, passes, fixedPoint, settled, horizon, deadShareZero, steps, censusFiles, derivedFiles, ok, checks }}
 */
export function deadShareChain(seedDir, { ticks = 200, tag = 'dead-share', verdictDir = path.join(BRAIN_ROOT, 'bench', 'verdicts'), maxRounds = 8, maxPasses = 4, horizon = true, wireHistory: history = null, heapMb = 4000, say = () => {}, timeoutMs = 10 * 60_000 } = {}) {
  const seed = path.resolve(BRAIN_ROOT, seedDir), name = path.basename(seed), vdir = path.resolve(BRAIN_ROOT, verdictDir);
  if (!existsSync(path.join(seed, 'manifest.json'))) throw new Error('dead-share: no manifest.json in ' + seed);
  if (!/^[a-z0-9-]+$/i.test(tag)) throw new Error('dead-share: the tag ' + tag + ' is not letters, digits and dashes (the census would rename its file)');
  mkdirSync(vdir, { recursive: true });
  const env = childEnv();
  const run = (args, what) => {
    const r = spawnSync(process.execPath, ['--max-old-space-size=' + heapMb, ...args], { cwd: BRAIN_ROOT, encoding: 'utf8', timeout: timeoutMs, maxBuffer: 64 << 20, env, windowsHide: true });
    const printed = ((r.stdout || '') + (r.stderr || '')).split(/\r?\n/).filter(Boolean);
    if (r.status !== 0) throw new Error('dead-share: ' + what + ' exited ' + r.status + (r.error ? ' (' + r.error.message + ')' : '') + ': ' + printed.slice(-4).join(' | '));
    return printed;
  };
  const manifest = () => JSON.parse(readFileSync(path.join(seed, 'manifest.json'), 'utf8'));
  const steps = [], censusFiles = [], derivedFiles = [];
  let ci = 0;
  const census = () => {
    const i = ci++;
    const t = tag + '-c' + i;
    run([path.join(BRAIN_ROOT, 'tools', 'organism-census.mjs'), '--seed', seed, '--ticks', String(ticks), '--no-knockout', '--tag', t, '--verdict-dir', vdir], 'census ' + t);
    const file = path.join(vdir, 'census-' + name + '-' + t + '-partial.json');
    const v = JSON.parse(readFileSync(file, 'utf8'));
    const h = manifest().hash;
    if (!v.live || v.live.manifestHash !== h) throw new Error('dead-share: ' + file + ' measured hash ' + (v.live && v.live.manifestHash) + ', the seed is ' + h);
    const row = censusRow(v, file);
    steps.push({ step: 'census', i, ...row });
    censusFiles.push(row.file);
    say('  census c' + i + ': lines ' + row.lines + ', load bearing ' + row.loadBearing + ', dead share ' + row.deadShare + '; cells ' + row.cells.declared + ' (ran ' + row.cells.ran + ', fired ' + row.cells.fired + '), edges ' + row.edges.declared + ' (delivered ' + row.edges.delivered + ', in flight at the end ' + (v.edges.inFlightAtEnd ?? 'n/a') + '); hosted score ' + row.score + '; drive delivered ' + (row.drive && row.drive.delivered) + ' (' + row.file + ')');
    return { file, row, v };
  };
  // what a prune by a census would drop: a cell that never ran, an edge that neither delivered nor was
  // in flight at the end (a protected one is kept too, so this can only overcount what would go)
  // (a cell the hosted problems chose is protected by the prune, so one that never ran is not counted:
  // a prune called for it alone drops nothing and only adds a round to the seed's record)
  const droppable = (v) => {
    const cells = readLiveBits(v.live.cells), edges = readLiveBits(v.live.edges), inFlight = v.live.inFlight ? readLiveBits(v.live.inFlight) : null;
    let n = cells.n - cells.count - hostedNeverRan(v, seedCellIds(seed)).length;
    for (let e = 0; e < edges.n; e++) if (!edges.has(e) && !(inFlight && inFlight.has(e))) n++;
    return n;
  };
  const hist = history && history.length ? ['--wire-history', history.join(',')] : [];
  const hz = { ran: 0, landed: 0, reverted: 0, withheld: 0, hostedNeverRan: [], cellsDropped: 0, edgesDropped: 0, moved: [] };
  // the horizon step on the seed as census c measured it; returns the census after it, or null
  const horizonStep = (c) => {
    const inFlight = c.v.live && c.v.live.inFlight ? c.v.live.inFlight.count : 0;
    const never = hostedNeverRan(c.v, seedCellIds(seed));
    if (!(c.row.deadShare > 0) || (inFlight === 0 && never.length === 0)) return null;
    hz.ran++;
    const derived = c.file.replace(/-partial\.json$/, '-horizon-partial.json');
    writeFileSync(derived, JSON.stringify(withheldAtHorizon(c.v, toPosix(path.relative(BRAIN_ROOT, c.file)), never), null, 2) + '\n');
    derivedFiles.push(toPosix(path.relative(BRAIN_ROOT, derived)));
    // a copy of the seed as it is, beside it (a dot name: the gate and the census skip it), so a step
    // that moved anything inside the horizon is put back
    const backup = path.join(path.dirname(seed), '.' + name + '.horizon-backup');
    rmSync(backup, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
    cpSync(seed, backup, { recursive: true });
    try {
      run([EMITTER, '--prune', derived, '--seed', seed, '--out', seed, '--name', name, ...hist], 'horizon prune');
      const p = manifest().genome.pruned;
      const h = census();
      const moved = horizonMoved(c.v, h.v);
      if (moved.length === 0) {
        hz.landed++; hz.withheld += inFlight; hz.hostedNeverRan.push(...never); hz.cellsDropped += p.cells.before - p.cells.after; hz.edgesDropped += p.edges.before - p.edges.after;
        steps.push({ step: 'horizon', withheldInFlight: inFlight, withheldHostedNeverRan: never, cells: p.cells, edges: p.edges, derived: toPosix(path.relative(BRAIN_ROOT, derived)), changedNothingInside: true });
        say('  horizon: withheld ' + inFlight + ' in flight edges and ' + never.length + ' chosen cells that never ran' + (never.length ? ' (' + never.join(', ') + ')' : '') + '; cells ' + p.cells.before + ' -> ' + p.cells.after + ', edges ' + p.edges.before + ' -> ' + p.edges.after + '; nothing inside the horizon moved (' + horizonWork(h.v).map(([n, x]) => n + ' ' + x).join(', ') + ')');
        rmSync(backup, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
        return h;
      }
      // put the seed back as census c measured it
      rmSync(seed, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
      retrying(() => renameSync(backup, seed));
      hz.reverted++; hz.moved.push(...moved);
      steps.push({ step: 'horizon', withheldInFlight: inFlight, withheldHostedNeverRan: never, reverted: true, moved });
      say('  horizon: REVERTED, the step moved ' + moved.join('; ') + '; the seed is put back as ' + c.row.file + ' measured it');
      return null;
    } finally {
      if (existsSync(backup) && existsSync(seed)) rmSync(backup, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
    }
  };
  say('dead-share ' + toPosix(path.relative(BRAIN_ROOT, seed)) + ' at ' + ticks + ' ticks, censuses to ' + toPosix(path.relative(BRAIN_ROOT, vdir)) + ' tagged ' + tag);
  let c = census();
  const first = c.row;
  let rounds = 0, fixedPoint = false, passes = 0, settled = false;
  for (let pass = 1; pass <= maxPasses; pass++) {
    passes = pass;
    let changed = false, passRounds = 0;
    fixedPoint = false;
    for (let r = 1; r <= maxRounds; r++) {
      const h0 = manifest().hash;
      const printed = run([EMITTER, '--wire', c.file, '--seed', seed, '--out', seed, '--name', name, ...hist], 'wire round ' + r);
      for (const line of printed) if (line.trimStart().startsWith('history ')) say(line);
      const m = manifest();
      if (m.hash === h0) { fixedPoint = true; steps.push({ step: 'wire', pass, round: r, portsWired: 0, fixedPoint: true }); say('  wire p' + pass + ' r' + r + ': nothing to wire, the fixed point'); break; }
      const w = m.genome.wired;
      steps.push({ step: 'wire', pass, round: r, portsWired: w.portsWired, cellsWired: w.cellsWired, edgesBefore: w.edgesBefore, edgesAfter: w.edgesAfter, portsNoDonor: w.portsNoDonor, clockSkipped: w.clockSkipped });
      say('  wire p' + pass + ' r' + r + ': wired ' + w.portsWired + ' ports, edges ' + w.edgesBefore + ' -> ' + w.edgesAfter + ' (no legal donor ' + w.portsNoDonor + ', clock skipped ' + w.clockSkipped + ')');
      rounds++; passRounds++; changed = true;
      c = census();
    }
    // a seed whose last census leaves nothing for the prune to drop and that wired nothing is left as it
    // is (a prune would only add a round to its record; rebuilt history, if any, the wire step wrote)
    const drop = droppable(c.v);
    if (drop > 0 || passRounds > 0) {
      run([EMITTER, '--prune', c.file, '--seed', seed, '--out', seed, '--name', name, ...hist], 'prune');
      const p = manifest().genome.pruned;
      steps.push({ step: 'prune', pass, cells: p.cells, edges: p.edges });
      say('  prune p' + pass + ': cells ' + p.cells.before + ' -> ' + p.cells.after + ', edges ' + p.edges.before + ' -> ' + p.edges.after + ' (never delivered ' + p.edges.neverDelivered + ')');
      changed = true;
      c = census();
    } else {
      steps.push({ step: 'prune', pass, skipped: 'the last census leaves nothing to drop (every cell ran, every edge delivered or was in flight at the end) and no round wired anything' });
      say('  prune p' + pass + ': nothing to drop and nothing wired; the seed is left as it is');
    }
    if (horizon) { const h = horizonStep(c); if (h) { c = h; changed = true; } }
    if (!changed) { settled = true; break; }
  }
  const last = c.row;
  // the chain's own checks; what dead share is enough (0 for one seed, the gate's cap for another)
  // is the caller's bar, so deadShareZero is reported and not required
  const checks = {
    fixedPoint, settled,
    deadShareDidNotRise: first.deadShare !== null && last.deadShare !== null && last.deadShare <= first.deadShare,
    hostedScoreDidNotFall: first.score !== null && last.score !== null && last.score >= first.score,
    algebraDidNotFall: last.algebra >= first.algebra, sequenceDidNotFall: last.sequence >= first.sequence,
    ...(hz.ran ? { horizonChangedNothingInside: hz.reverted === 0 } : {}),
  };
  const ok = Object.values(checks).every(Boolean);
  const deadShareZero = last.deadShare === 0;
  say('  dead share ' + first.deadShare + ' -> ' + last.deadShare + ', lines ' + first.lines + ' -> ' + last.lines + ', hosted score ' + first.score + ' -> ' + last.score + ', wire rounds ' + rounds + (fixedPoint ? ' to the fixed point' : ' (max rounds reached before the fixed point)') + ', passes ' + passes + (settled ? ' (the last changed nothing)' : ' (max passes reached, still changing)') + ', horizon ' + (hz.ran ? 'withheld ' + hz.withheld + ' in flight edges and ' + hz.hostedNeverRan.length + ' chosen cells that never ran, dropped ' + hz.edgesDropped + ' edges and ' + hz.cellsDropped + ' cells' + (hz.reverted ? ', reverted ' + hz.reverted : '') : 'not needed') + ': ' + (ok ? 'OK' : 'NOT MET (' + Object.entries(checks).filter(([, v]) => !v).map(([k]) => k).join(', ') + ')'));
  return { seed: toPosix(path.relative(BRAIN_ROOT, seed)), ticks, first, last, rounds, passes, fixedPoint, settled, horizon: hz, deadShareZero, steps, censusFiles, derivedFiles, checks, ok };
}

/**
 * The chain over every seed under a root (default organism/), one seed at a time, in name order. A
 * seed is skipped by name when its manifest declares more than maxCells cells (the census bar's
 * --max-cells) or when it is named in skip; nothing of a skipped seed is loaded.
 * @param {{ root?, maxCells?, skip?: string[], say?, ...chainOpts }} [opts]
 * @returns {{ rows: Array<object>, skipped: Array<{ seed, why }>, ok: boolean }}
 */
export function deadShareAll({ root = path.join(BRAIN_ROOT, 'organism'), maxCells = 1000, skip = [], say = () => {}, ...opts } = {}) {
  const rows = [], skipped = [];
  for (const d of readdirSync(root).sort()) {
    const dir = path.join(root, d);
    if (d.startsWith('.') || !existsSync(path.join(dir, 'index.mjs')) || !existsSync(path.join(dir, 'manifest.json'))) continue;
    const seedName = toPosix(path.relative(BRAIN_ROOT, dir));
    if (skip.includes(d) || skip.includes(seedName)) { skipped.push({ seed: seedName, why: 'named in --skip' }); say('skip ' + d + ': named in --skip'); continue; }
    const cells = JSON.parse(readFileSync(path.join(dir, 'manifest.json'), 'utf8')).counts.cells;
    if (cells > maxCells) { skipped.push({ seed: seedName, why: 'cells ' + cells + ' over --max-cells ' + maxCells }); say('skip ' + d + ': ' + cells + ' cells is over --max-cells ' + maxCells); continue; }
    const t0 = Date.now();
    try { rows.push({ ...deadShareChain(dir, { say, ...opts }), wallS: (Date.now() - t0) / 1000 }); } catch (err) { rows.push({ seed: seedName, error: err.message, ok: false, wallS: (Date.now() - t0) / 1000 }); say('  ' + seedName + ': ' + err.message); }
  }
  const zero = rows.filter((r) => r.deadShareZero).length;
  say('dead-share --all: ' + rows.length + ' seeds chained, ' + rows.filter((r) => r.ok).length + ' OK, ' + zero + ' at dead share 0; skipped ' + skipped.length + (skipped.length ? ' (' + skipped.map((s) => s.seed + ': ' + s.why).join('; ') + ')' : ''));
  return { rows, skipped, ok: rows.length > 0 && rows.every((r) => r.ok) };
}

export function deadShareMain(argv) {
  const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
  const say = argv.includes('--quiet') ? () => {} : (s) => process.stdout.write(s + '\n');
  const hist = opt('wire-history', '');
  const common = {
    ticks: Number(opt('ticks', 200)), tag: opt('tag', 'dead-share'), verdictDir: opt('verdict-dir', path.join(BRAIN_ROOT, 'bench', 'verdicts')),
    maxRounds: Number(opt('max-rounds', 8)), maxPasses: Number(opt('max-passes', 4)), horizon: !argv.includes('--keep-in-flight'), say,
  };
  if (argv.includes('--all')) {
    if (hist) throw new Error('dead-share --all: --wire-history names one seed\'s censuses; give it with --dead-share organism/<seed>');
    return deadShareAll({ ...common, maxCells: Number(opt('max-cells', 1000)), skip: String(opt('skip', '')).split(',').filter(Boolean) });
  }
  const seedDir = opt('dead-share', '');
  if (!seedDir) throw new Error('dead-share: name the seed (--dead-share organism/<seed>) or --all');
  const r = deadShareChain(seedDir, { ...common, wireHistory: hist ? hist.split(',') : null });
  // --json <file>: the chain's whole result, for a caller that ran it as a child (bench/dead-share-all.mjs)
  const json = opt('json', '');
  if (json) { mkdirSync(path.dirname(path.resolve(BRAIN_ROOT, json)), { recursive: true }); writeFileSync(path.resolve(BRAIN_ROOT, json), JSON.stringify(r, null, 2) + '\n'); }
  return r;
}

// ---------------------------------------------------------------- streaming (MANUAL P8, Board 12)
//
// organism/scale-52000 is 5,125,448 lines and a whole load of it sat at 5839.8 MB before its
// first tick. Everything below reads an emitted seed line by line through a fixed buffer and
// never builds a Brain: the static census (tools/organism-census.mjs --static) and the prune
// by it (pruneStatic) both run in a few hundred MB whatever the seed's size.

/**
 * Stream a text file line by line through a fixed buffer. fn(line) is called for every piece
 * text.split('\n') would give (a trailing carriage return removed), the last one included.
 * Returns the physical line count the way bench/gate.mjs counts it: the newlines plus one.
 * @param {string} file @param {(line: string) => void} fn
 * @param {{ chunkBytes?: number }} [opts]
 */
export function eachLine(file, fn, { chunkBytes = 1 << 20 } = {}) {
  const fd = openSync(file, 'r');
  const buf = Buffer.allocUnsafe(chunkBytes);
  const dec = new StringDecoder('utf8');
  const strip = (s) => (s.length && s.charCodeAt(s.length - 1) === 13 ? s.slice(0, -1) : s);
  let carry = '', lines = 1;
  try {
    for (;;) {
      const n = readSync(fd, buf, 0, chunkBytes, null);
      if (n <= 0) break;
      const s = carry + dec.write(buf.subarray(0, n));
      let i = 0, j;
      while ((j = s.indexOf('\n', i)) >= 0) { lines++; fn(strip(s.slice(i, j))); i = j + 1; }
      carry = s.slice(i);
    }
    carry += dec.end();
    fn(strip(carry));
  } finally { closeSync(fd); }
  return lines;
}

/** The arguments of one declaration line, `pre(...);`, as the JSON array genome/emit.mjs wrote. */
export function declArgs(line, pre) {
  if (!line.endsWith(');')) throw new Error('emit: a declaration line does not end in ");": ' + line.slice(0, 80));
  return JSON.parse('[' + line.slice(pre.length, -2) + ']');
}

// The content hash (genome/wire.mjs contentHash) over declaration lines instead of a Brain. A
// loaded cell's params are its kind's defaults under the line's params and its policy is
// DEFAULT_POLICY under the line's policy (core/cell.mjs createCell); a loaded edge keeps its
// ports in Uint8Array, its delay in Uint16Array and its weight and confidence in Float32Array
// (core/connectome.mjs), and the hash prints them through f32. The same rows, so the same hash:
// checked on organism/scale-52000, whose manifest hash was computed on a real Brain.
const U8 = new Uint8Array(1), U16 = new Uint16Array(1);
export function cellHashRow(id, kind, region, circuit, params, policy) {
  const k = getKind(kind);
  return JSON.stringify([id, k.name, region || 'default', circuit || 'default', stable({ ...(k.defaults || {}), ...(params || {}) }), stable({ ...DEFAULT_POLICY, ...(policy || {}) })]) + '\n';
}
export function edgeHashRow(src, dst, sp, dp, w, delay, conf) {
  U8[0] = sp; const a = U8[0]; U8[0] = dp; const b = U8[0]; U16[0] = delay;
  return JSON.stringify([src, dst, a, b, f32(w), U16[0], f32(conf === undefined ? 0.5 : conf)]) + '\n';
}

/** index.mjs of an emitted seed names its cells and edges files in load order. */
export function seedFiles(dir) {
  const abs = path.resolve(dir);
  const text = readFileSync(path.join(abs, 'index.mjs'), 'utf8');
  return {
    cells: [...text.matchAll(/from "\.\/(cells-\d+\.mjs)"/g)].map((m) => m[1]),
    edges: [...text.matchAll(/from "\.\/(edges-\d+\.mjs)"/g)].map((m) => m[1]),
  };
}

// The same file templates emitOrganism writes, for a seed written line by line. A test holds
// the two byte for byte (test/census-static.test.mjs), so they cannot drift apart unseen.
const regionsHeadOf = (name, nCircuits, nRegions) => [
  '// ' + name + '/regions.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
  '// The regions of the organism and the circuits inside them. A circuit is a major',
  '// computational node: ' + nCircuits + ' of them here, across ' + nRegions + ' regions.',
  '// r(name, { budget, doc }); budget null means unbounded. k(region, name, period, doc).',
  'export default function regions(r, k) {',
];
const cellsHeadOf = (name, total) => (i, lo, hi) => [
  '// ' + name + '/cells-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
  '// Cells ' + lo + ' to ' + (hi - 1) + ' of ' + total + '.',
  '// c(id, kind, region, circuit, params, policy)',
  'export default function cells(c) {',
];
const edgesHeadOf = (name, total) => (i, lo, hi) => [
  '// ' + name + '/edges-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
  '// Edges ' + lo + ' to ' + (hi - 1) + ' of ' + total + '. THE CONNECTOME IS THE BULK OF THE ORGANISM.',
  '// e(src, dst, srcPort, dstPort, w, delay, conf); conf is omitted when it is the 0.5 default.',
  'export default function edges(e) {',
];

/** emitChunks, one line at a time: the same file boundaries and the same text. */
class ChunkStream {
  constructor({ write, split, prefix, total, head }) {
    Object.assign(this, { write, prefix, total, head, names: [], buf: null, file: 0, lo: 0, hi: 0, n: 0 });
    this.perFile = Math.max(1, split - head(0, 0, 0).length - 2);
    if (total === 0) { const L = head(0, 0, 0); L.push('}'); const nm = this.fileName(0); write(nm, L); this.names.push(nm); }
  }
  fileName(i) { return this.prefix + '-' + pad3(i) + '.mjs'; }
  push(line) {
    if (this.n >= this.total) throw new Error('emit: more lines pushed than the ' + this.total + ' declared');
    if (!this.buf) { this.lo = this.n; this.hi = Math.min(this.total, this.lo + this.perFile); this.buf = this.head(this.file, this.lo, this.hi); }
    this.buf.push(line); this.n++;
    if (this.n === this.hi) { this.buf.push('}'); const nm = this.fileName(this.file); this.write(nm, this.buf); this.names.push(nm); this.buf = null; this.file++; }
  }
  end() {
    if (this.n !== this.total) throw new Error('emit: ' + this.n + ' lines pushed, ' + this.total + ' declared');
    return this.names;
  }
}

/**
 * Prune an emitted seed WITHOUT loading it: every c() and e() line whose liveness bit is set is
 * copied verbatim into a new seed, re-chunked, and the new manifest's content hash is computed
 * over the same rows contentHash reads. The keep rule is pruneBrain's: every live cell, every
 * live edge (and every edge in flight, when recorded), both endpoints of every kept edge, the
 * protected cells, and the regions and circuits that still hold a kept cell.
 * @param {object} o
 * @param {string} o.seedDir the seed to prune
 * @param {{cells: {n, has}, edges: {n, has}, inFlight?: {n, has}}} o.live readers from readLiveBits
 * @param {string} o.outDir @param {string} [o.name] @param {number} [o.split] lines per file,
 *   default the largest cells or edges file of the source
 * @param {string[]} [o.protect] cell ids kept whatever their liveness
 * @param {object} [o.note] recorded as genome.pruned.census
 * @returns the summary printed by pruneStaticMain
 */
export function pruneStatic({ seedDir, live, outDir, name = null, split = null, protect = [], note = null, rule = 'static' }) {
  const t0 = Date.now();
  const src = path.resolve(seedDir);
  const manifest = JSON.parse(readFileSync(path.join(src, 'manifest.json'), 'utf8'));
  const files = seedFiles(src);
  const nC = manifest.counts.cells, nE = manifest.counts.edges;
  if (live.cells.n !== nC) throw new Error('prune: liveness covers ' + live.cells.n + ' cells, the manifest counts ' + nC);
  if (live.edges.n !== nE) throw new Error('prune: liveness covers ' + live.edges.n + ' edges, the manifest counts ' + nE);
  if (live.inFlight && live.inFlight.n !== nE) throw new Error('prune: in flight liveness covers ' + live.inFlight.n + ' edges, the manifest counts ' + nE);
  const outName = name || path.basename(src) + '-pruned';
  const out = path.resolve(outDir);
  if (out === src) throw new Error('prune: the output directory is the seed itself');
  if (!split) split = Math.max(...manifest.files.filter((f) => /^(cells|edges)-/.test(f.path)).map((f) => f.lines));
  // regions.mjs: the declared regions and circuits, in order
  const rLines = [], kLines = [], circuitIdx = new Map(), regionIdx = new Map();
  eachLine(path.join(src, 'regions.mjs'), (l) => {
    if (l.startsWith('r(')) { const a = declArgs(l, 'r('); regionIdx.set(a[0], rLines.length); rLines.push(l); }
    else if (l.startsWith('k(')) { const a = declArgs(l, 'k('); circuitIdx.set(a[0] + '/' + a[1], { i: kLines.length, region: a[0] }); kLines.push(l); }
  });
  // pass A: every cell, its circuit, and whether its own bit keeps it
  const keep = new Uint8Array(nC), circuitOf = new Int32Array(nC);
  const idOf = new Map(), prot = new Set(protect);
  let g = 0, ran = 0, protectedOnly = 0, endpointOnly = 0;
  for (const f of files.cells) eachLine(path.join(src, f), (l) => {
    if (!l.startsWith('c(')) return;
    const [id, , region, circuit] = declArgs(l, 'c(');
    if (g >= nC) throw new Error('prune: ' + f + ' declares more cells than the manifest counts (' + nC + ')');
    const c = circuitIdx.get((region || 'default') + '/' + (circuit || 'default'));
    if (!c) throw new Error('prune: cell ' + id + ' names circuit ' + region + '/' + circuit + ', which regions.mjs does not declare');
    idOf.set(id, g); circuitOf[g] = c.i;
    if (live.cells.has(g)) { keep[g] = 1; ran++; } else if (prot.has(id)) { keep[g] = 1; protectedOnly++; }
    g++;
  });
  if (g !== nC) throw new Error('prune: the seed declares ' + g + ' cells, its manifest counts ' + nC);
  // pass B: which edges are kept, and the endpoints they keep
  let j = 0, delivered = 0, inFlightOnly = 0;
  for (const f of files.edges) eachLine(path.join(src, f), (l) => {
    if (!l.startsWith('e(')) return;
    const e = j++;
    if (live.edges.has(e)) delivered++; else if (live.inFlight && live.inFlight.has(e)) inFlightOnly++; else return;
    const x = declArgs(l, 'e(');
    for (const id of [x[0], x[1]]) {
      const i = idOf.get(id);
      if (i === undefined) throw new Error('prune: edge ' + e + ' names an undeclared cell ' + id);
      if (!keep[i]) { keep[i] = 1; endpointOnly++; }
    }
  });
  if (j !== nE) throw new Error('prune: the seed declares ' + j + ' edges, its manifest counts ' + nE);
  const keptEdges = delivered + inFlightOnly;
  let keptCells = 0;
  const liveCircuit = new Uint8Array(kLines.length), liveRegion = new Uint8Array(rLines.length);
  const circuitRegion = new Int32Array(kLines.length);
  for (const c of circuitIdx.values()) { const r = regionIdx.get(c.region); circuitRegion[c.i] = r === undefined ? -1 : r; }
  for (let i = 0; i < nC; i++) if (keep[i]) { keptCells++; liveCircuit[circuitOf[i]] = 1; const r = circuitRegion[circuitOf[i]]; if (r >= 0) liveRegion[r] = 1; }
  const nRegions = liveRegion.reduce((a, b) => a + b, 0), nCircuits = liveCircuit.reduce((a, b) => a + b, 0);
  // pass C: write the copy and hash it on the way
  if (existsSync(out)) rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const written = [];
  const write = (file, lines) => {
    const text = lines.join('\n') + '\n';
    writeFileSync(path.join(out, file), text);
    const n = text.split('\n').length;
    written.push({ path: file, lines: n, bytes: Buffer.byteLength(text), sha256: createHash('sha256').update(text).digest('hex') });
    return n;
  };
  {
    const L = regionsHeadOf(outName, nCircuits, nRegions);
    rLines.forEach((l, i) => { if (liveRegion[i]) L.push(l); });
    kLines.forEach((l, i) => { if (liveCircuit[i]) L.push(l); });
    L.push('}');
    if (L.length + 1 > split) throw new Error('prune: regions.mjs would be ' + (L.length + 1) + ' lines, over the ' + split + ' line split');
    write('regions.mjs', L);
  }
  const h = createHash('sha256');
  h.update('brain.genome.v1\n');
  h.update('cells ' + keptCells + '\n');
  const cs = new ChunkStream({ write, split, prefix: 'cells', total: keptCells, head: cellsHeadOf(outName, keptCells) });
  g = 0;
  for (const f of files.cells) eachLine(path.join(src, f), (l) => {
    if (!l.startsWith('c(')) return;
    if (keep[g++]) { const a = declArgs(l, 'c('); h.update(cellHashRow(...a)); cs.push(l); }
  });
  const cellFiles = cs.end();
  h.update('edges ' + keptEdges + '\n');
  const es = new ChunkStream({ write, split, prefix: 'edges', total: keptEdges, head: edgesHeadOf(outName, keptEdges) });
  j = 0;
  for (const f of files.edges) eachLine(path.join(src, f), (l) => {
    if (!l.startsWith('e(')) return;
    const e = j++;
    if (!(live.edges.has(e) || (live.inFlight && live.inFlight.has(e)))) return;
    const x = declArgs(l, 'e(');
    h.update(edgeHashRow(...x)); es.push(l);
  });
  const edgeFiles = es.end();
  const hash = h.digest('hex');
  const { loaded, hash: oldHash, wiring, pruned: priorPrune, ...genome0 } = manifest.genome || {};
  const regionsDropped = rLines.length - nRegions, circuitsDropped = kLines.length - nCircuits;
  const genome = {
    ...genome0, name: outName,
    pruned: {
      from: manifest.name, fromHash: manifest.hash, rule, streamed: true,
      cells: { before: nC, after: keptCells },
      edges: { before: nE, after: keptEdges, neverDelivered: nE - keptEdges, orphaned: 0 },
      kept: { cells: { ran, protectedOnly, endpointOnly }, edges: { delivered, inFlightOnly, protectedOnly: 0, inFlightRecorded: !!live.inFlight }, protect: { cells: prot.size, edges: 0 } },
      regionsDropped, circuitsDropped,
      wiring: null,
      ...(note ? { census: note } : {}),
    },
  };
  const counts = { regions: nRegions, circuits: nCircuits, cells: keptCells, edges: keptEdges, cellFiles: cellFiles.length, edgeFiles: edgeFiles.length };
  {
    const rel = toPosix(path.relative(out, BRAIN_ROOT)) || '.';
    const L = [
      '// ' + outName + '/index.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// The organism as source. load() returns a Brain wired exactly as it was emitted.',
      'import { loadOrganism } from ' + J(rel + '/genome/load.mjs') + ';',
      'import regions from ' + J('./regions.mjs') + ';',
    ];
    for (const f of cellFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    for (const f of edgeFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    L.push('');
    L.push('export const meta = ' + JSON.stringify({ name: outName, seed: genome.seed ?? outName, genome, counts, hash }) + ';');
    L.push('export const parts = { regions, cells: [' + cellFiles.map(ident).join(', ') + '], edges: [' + edgeFiles.map(ident).join(', ') + '] };');
    L.push('export function load(opts = {}) { return loadOrganism(parts, meta, opts); }');
    L.push('export default load;');
    write('index.mjs', L);
  }
  const lines = written.reduce((a, f) => a + f.lines, 0);
  const bytes = written.reduce((a, f) => a + f.bytes, 0);
  const m = {
    format: 'brain.genome.v1',
    name: outName, seed: genome.seed ?? outName, genome,
    counts: { ...counts, files: written.length + 1, lines, bytes },
    hash,
    files: written.slice().sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0),
  };
  const mtext = JSON.stringify(m, null, 2) + '\n';
  writeFileSync(path.join(out, 'manifest.json'), mtext);
  return {
    dir: out, name: outName, split, hash, counts,
    lines: { before: manifest.counts.lines, after: lines, manifestFileLines: mtext.split('\n').length },
    bytes: { before: manifest.counts.bytes, after: bytes, manifest: Buffer.byteLength(mtext), onDisk: bytes + Buffer.byteLength(mtext) },
    cells: { before: nC, after: keptCells, kept: { ran, protectedOnly, endpointOnly }, dropped: nC - keptCells },
    edges: { before: nE, after: keptEdges, kept: { delivered, inFlightOnly }, dropped: nE - keptEdges },
    regionsDropped, circuitsDropped, files: written.length + 1, ms: Date.now() - t0,
  };
}

// node genome/emit.mjs --prune <a static census verdict> [--out dir] [--name n] [--split N]
async function pruneStaticMain(argv, census, censusFile) {
  const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
  const say = argv.includes('--quiet') ? () => {} : (s) => process.stdout.write(s + '\n');
  await import('../cells/all.mjs');
  const seedDir = path.resolve(BRAIN_ROOT, opt('seed', census.seed));
  const manifest = JSON.parse(readFileSync(path.join(seedDir, 'manifest.json'), 'utf8'));
  if (census.live.manifestHash !== manifest.hash) throw new Error('prune: the census was taken on organism hash ' + census.live.manifestHash + ', ' + seedDir + ' has ' + manifest.hash);
  const name = opt('name', path.basename(seedDir) + '-pruned');
  const outDir = path.resolve(opt('out', path.join(BRAIN_ROOT, 'bench', 'verdicts', '.census', name)));
  const cells = readLiveBits(census.live.cells), edges = readLiveBits(census.live.edges);
  const r = pruneStatic({
    seedDir, live: { cells, edges }, outDir, name, split: Number(opt('split', 0)) || null,
    protect: census.hosted || [],
    note: { file: toPosix(path.relative(BRAIN_ROOT, censusFile)), at: census.at, rule: census.live.phases, command: census.command },
  });
  const pc = (a, b) => (100 * a / b).toFixed(2);
  say('prune ' + toPosix(path.relative(BRAIN_ROOT, seedDir)) + ' by ' + toPosix(path.relative(BRAIN_ROOT, censusFile)) + ' (static census at ' + census.at + '), streamed line by line, never loaded');
  say('  lines ' + r.lines.before + ' -> ' + r.lines.after + ' (manifest count: every emitted file but manifest.json): ' + (r.lines.before - r.lines.after) + ' removed, ' + pc(r.lines.before - r.lines.after, r.lines.before) + '% of the seed');
  say('  cells ' + r.cells.before + ' -> ' + r.cells.after + ': kept ' + r.cells.kept.ran + ' live, ' + r.cells.kept.protectedOnly + ' protected only, ' + r.cells.kept.endpointOnly + ' endpoint only; dropped ' + r.cells.dropped);
  say('  edges ' + r.edges.before + ' -> ' + r.edges.after + ': kept ' + r.edges.kept.delivered + ' live; dropped ' + r.edges.dropped);
  say('  regions dropped ' + r.regionsDropped + ', circuits dropped ' + r.circuitsDropped + '; split ' + r.split + ' lines per file');
  say('  emitted ' + toPosix(path.relative(BRAIN_ROOT, r.dir)) + ': ' + r.files + ' files, ' + r.bytes.onDisk + ' bytes on disk (' + r.bytes.after + ' before the manifest; the source had ' + r.bytes.before + '), content hash ' + r.hash.slice(0, 16));
  say('  in ' + (r.ms / 1000).toFixed(1) + ' s; census the copy with tools/organism-census.mjs --static --seed ' + toPosix(path.relative(BRAIN_ROOT, r.dir)));
  return { ok: true, ...r };
}

// ---------------------------------------------------------------- prune on a copy (Board 14)
//
// The autopilot's census wall: every prune of a pinned seed was refused because the seed is
// re-emitted whole by `node genome/emit.mjs --prune` and nothing authored that call. This
// authors it, on a COPY of the tree only. It runs the COPY's own emit.mjs as a child process,
// so the pruned seed's index.mjs imports the copy's genome/load.mjs and every path the prune
// records is the copy's; calling pruneMain in this process would have written an index that
// imports THIS tree's loader. A root that is the tree this file lives in is refused: the
// real tree is never written by it.

const samePath = (a, b) => (process.platform === 'win32' ? path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase() : path.resolve(a) === path.resolve(b));
const inside = (dir, p) => { const r = path.relative(dir, p); return !!r && !r.startsWith('..') && !path.isAbsolute(r); };

/**
 * Prune one seed of a copy of the tree by a census, with the copy's own emitter.
 * @param {string} root the copy's root (it must hold genome/emit.mjs); never this tree
 * @param {string} seedDir the seed to prune, inside root/organism/ (relative to root or absolute)
 * @param {string} outDir where the pruned seed is written, inside root/organism/, never the seed
 * @param {string|object} census a census verdict: a path (relative to root, or absolute) or the
 *   parsed verdict, which is then written into the copy (bench/verdicts/.census/) first
 * @param {{ heapMb?: number, timeoutMs?: number, name?: string }} [opts]
 * @returns {{ ok, exit, dir, name, censusFile, hash, lines: {before, after}, cells: {before, after},
 *   edges: {before, after}, manifest, printed: string[], ms, error }}
 */
export function pruneOnCopy(root, seedDir, outDir, census, { heapMb = 6000, timeoutMs = 30 * 60_000, name = null } = {}) {
  const t0 = Date.now();
  const R = path.resolve(root);
  if (samePath(R, BRAIN_ROOT)) throw new Error('pruneOnCopy: ' + R + ' is the tree this emitter lives in; it prunes a copy only');
  const emitter = path.join(R, 'genome', 'emit.mjs');
  if (!existsSync(emitter)) throw new Error('pruneOnCopy: the copy has no genome/emit.mjs at ' + emitter);
  const org = path.join(R, 'organism');
  const seed = path.resolve(R, seedDir), out = path.resolve(R, outDir);
  if (!inside(org, seed)) throw new Error('pruneOnCopy: the seed ' + seed + ' is not inside the copy\'s organism/');
  if (!inside(org, out)) throw new Error('pruneOnCopy: the output ' + out + ' is not inside the copy\'s organism/');
  if (samePath(seed, out)) throw new Error('pruneOnCopy: the output directory is the seed itself');
  if (!existsSync(path.join(seed, 'manifest.json'))) throw new Error('pruneOnCopy: no manifest.json in ' + seed);
  const nm = name || path.basename(out);
  let censusFile;
  if (typeof census === 'string') censusFile = path.resolve(R, census);
  else if (census && typeof census === 'object') {
    const d = path.join(R, 'bench', 'verdicts', '.census');
    mkdirSync(d, { recursive: true });
    censusFile = path.join(d, nm + '.census.json');
    writeFileSync(censusFile, JSON.stringify(census));
  } else throw new Error('pruneOnCopy: census must be a path or a parsed census verdict');
  if (!existsSync(censusFile)) throw new Error('pruneOnCopy: no census file at ' + censusFile);
  const before = JSON.parse(readFileSync(path.join(seed, 'manifest.json'), 'utf8'));
  const env = {};
  for (const [k, v] of Object.entries(process.env)) if (!k.startsWith('NODE_TEST') && k !== 'NODE_OPTIONS') env[k] = v;
  const r = spawnSync(process.execPath, ['--max-old-space-size=' + heapMb, emitter, '--prune', censusFile, '--seed', seed, '--out', out, '--name', nm], {
    cwd: R, encoding: 'utf8', timeout: timeoutMs, maxBuffer: 64 * 1024 * 1024, env, windowsHide: true,
  });
  const printed = ((r.stdout || '') + (r.stderr || '')).split(/\r?\n/).filter(Boolean);
  const mf = path.join(out, 'manifest.json');
  const after = r.status === 0 && existsSync(mf) ? JSON.parse(readFileSync(mf, 'utf8')) : null;
  const ok = r.status === 0 && !!after && !printed.some((l) => /ROUND TRIP FAILED/.test(l));
  const n = (m, k) => (m && m.counts ? m.counts[k] : null);
  return {
    ok, exit: r.status, dir: out, name: nm, censusFile, hash: after ? after.hash : null,
    lines: { before: n(before, 'lines'), after: n(after, 'lines') },
    cells: { before: n(before, 'cells'), after: n(after, 'cells') },
    edges: { before: n(before, 'edges'), after: n(after, 'edges') },
    manifest: after, printed, ms: Date.now() - t0,
    error: ok ? null : (r.error ? String(r.error.message) : 'emit.mjs --prune exited ' + r.status + ': ' + printed.slice(-3).join(' | ')),
  };
}

