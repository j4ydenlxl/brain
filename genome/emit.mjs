// genome/emit.mjs: WRITE THE ORGANISM AS SOURCE.
//
// A brain that exists only as the output of a builder is a brain nobody can read, diff,
// review or hand to someone else. This writes one out as ES modules: one `c(...)` call per
// cell and one `e(...)` call per edge, one per line, split into files of at most 20,000
// lines, plus a `regions.mjs` that declares the regions and circuits, an `index.mjs` that
// imports them in order and exports `load()`, and a `manifest.json` with the counts and a
// content hash over every one of those lines.
//
// The emitted source is the genome: structure, parameters, policy, weights, delays. It is
// not a snapshot. Runtime state, mailboxes, the clock and the ledger belong to
// Brain.snapshot; the genome is what the organism IS, the snapshot is where it HAD GOT TO.
//
// Weights and delays are exact. Connectome.w and .conf are Float32Array, and f32() prints
// the shortest decimal that Math.fround reads back to the identical float32, so loading the
// emitted source reproduces the connectome bit for bit and the content hash agrees.
import { mkdirSync, writeFileSync, rmSync, existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { f32, contentHash, Wiring, monomorphicGrowth } from './wire.mjs';
import { Brain } from '../core/brain.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BRAIN_ROOT = path.resolve(HERE, '..');
export const DEFAULT_SPLIT = 20000;

/**
 * Write a brain out as source.
 * @param {object} brain
 * @param {object} [opts]
 * @param {string} [opts.dir] output directory, default brain/organism/<brain.name>
 * @param {number} [opts.split] maximum physical lines per emitted file
 * @param {boolean} [opts.clean] remove the directory first, default true
 * @returns {{ dir, files, lines, bytes, counts, hash, manifest }}
 */
export function emitOrganism(brain, { dir = null, split = DEFAULT_SPLIT, clean = true, prune = null } = {}) {
  // prune is opt in and off by default: { cells, edges } liveness readers from readLiveBits,
  // plus pruneBrain's options. Without it the brain is written exactly as before.
  if (prune) brain = pruneBrain(brain, prune, prune).brain;
  const name = brain.name;
  const out = dir ? path.resolve(dir) : path.join(BRAIN_ROOT, 'organism', name);
  if (clean && existsSync(out)) rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const genome = brain.genome || {};
  const k = brain.connectome;
  const files = [];
  const write = (file, lines) => {
    const text = lines.join('\n') + '\n';
    writeFileSync(path.join(out, file), text);
    // Counted exactly the way bench/gate.mjs counts: physical lines of the file as written.
    const n = text.split('\n').length;
    files.push({ path: file, lines: n, bytes: Buffer.byteLength(text), sha256: createHash('sha256').update(text).digest('hex') });
    return n;
  };

  // ------------------------------------------------------------ regions.mjs
  {
    const L = [
      '// ' + name + '/regions.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// The regions of the organism and the circuits inside them. A circuit is a major',
      '// computational node: ' + brain.circuits.size + ' of them here, across ' + brain.regions.size + ' regions.',
      '// r(name, { budget, doc }); budget null means unbounded. k(region, name, period, doc).',
      'export default function regions(r, k) {',
    ];
    for (const rg of brain.regions.values()) {
      L.push('r(' + J(rg.name) + ',{"budget":' + (Number.isFinite(rg.budget) ? rg.budget : 'null') + ',"doc":' + J(rg.doc || '') + '});');
    }
    for (const c of brain.circuits.values()) {
      L.push('k(' + J(c.region) + ',' + J(c.name) + ',' + J(c.period) + ',' + J(c.doc || '') + ');');
    }
    L.push('}');
    if (L.length + 1 > split) throw new Error('emit: regions.mjs would be ' + (L.length + 1) + ' lines, over the ' + split + ' line split');
    write('regions.mjs', L);
  }

  // ------------------------------------------------------------ cells-NNN.mjs
  const cellFiles = emitChunks({
    write, split, prefix: 'cells', total: brain.cells.length,
    head: (i, lo, hi) => [
      '// ' + name + '/cells-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// Cells ' + lo + ' to ' + (hi - 1) + ' of ' + brain.cells.length + '.',
      '// c(id, kind, region, circuit, params, policy)',
      'export default function cells(c) {',
    ],
    line: (i) => {
      const c = brain.cells[i];
      return 'c(' + J(c.id) + ',' + J(c.kind) + ',' + J(c.region) + ',' + J(c.circuit) + ',' + JSON.stringify(c.params) + ',' + JSON.stringify(c.policy) + ');';
    },
  });

  // ------------------------------------------------------------ edges-NNN.mjs
  const edgeFiles = emitChunks({
    write, split, prefix: 'edges', total: k.n,
    head: (i, lo, hi) => [
      '// ' + name + '/edges-' + pad3(i) + '.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// Edges ' + lo + ' to ' + (hi - 1) + ' of ' + k.n + '. THE CONNECTOME IS THE BULK OF THE ORGANISM.',
      '// e(src, dst, srcPort, dstPort, w, delay, conf); conf is omitted when it is the 0.5 default.',
      'export default function edges(e) {',
    ],
    line: (i) => {
      const conf = Math.fround(k.conf[i]);
      return 'e(' + J(brain.cells[k.src[i]].id) + ',' + J(brain.cells[k.dst[i]].id) + ',' + k.srcPort[i] + ',' + k.dstPort[i] +
        ',' + f32(k.w[i]) + ',' + k.delay[i] + (conf === 0.5 ? '' : ',' + f32(conf)) + ');';
    },
  });

  // ------------------------------------------------------------ index.mjs
  const hash = contentHash(brain);
  const counts = {
    regions: brain.regions.size, circuits: brain.circuits.size,
    cells: brain.cells.length, edges: k.n,
    cellFiles: cellFiles.length, edgeFiles: edgeFiles.length,
  };
  {
    const rel = toPosix(path.relative(out, BRAIN_ROOT)) || '.';
    const L = [
      '// ' + name + '/index.mjs: GENERATED by genome/emit.mjs. Do not edit by hand.',
      '// The organism as source. load() returns a Brain wired exactly as it was emitted.',
      'import { loadOrganism } from ' + J(rel + '/genome/load.mjs') + ';',
      'import regions from ' + J('./regions.mjs') + ';',
    ];
    for (const f of cellFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    for (const f of edgeFiles) L.push('import ' + ident(f) + ' from ' + J('./' + f) + ';');
    L.push('');
    L.push('export const meta = ' + JSON.stringify({ name, seed: genome.seed ?? name, genome, counts, hash }) + ';');
    L.push('export const parts = { regions, cells: [' + cellFiles.map(ident).join(', ') + '], edges: [' + edgeFiles.map(ident).join(', ') + '] };');
    L.push('export function load(opts = {}) { return loadOrganism(parts, meta, opts); }');
    L.push('export default load;');
    write('index.mjs', L);
  }

  // ------------------------------------------------------------ manifest.json
  const lines = files.reduce((a, f) => a + f.lines, 0);
  const bytes = files.reduce((a, f) => a + f.bytes, 0);
  const manifest = {
    format: 'brain.genome.v1',
    name, seed: genome.seed ?? name, genome,
    counts: { ...counts, files: files.length + 1, lines, bytes },
    hash,
    files: files.slice().sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0),
  };
  const mtext = JSON.stringify(manifest, null, 2) + '\n';
  writeFileSync(path.join(out, 'manifest.json'), mtext);
  manifest.counts.lines += mtext.split('\n').length;

  return { dir: out, files: manifest.files, lines: manifest.counts.lines, bytes, counts, hash, manifest };
}

// Write `total` lines in chunks that never exceed `split` physical lines per file.
function emitChunks({ write, split, prefix, total, head, line }) {
  const names = [];
  const probe = head(0, 0, 0);
  const perFile = Math.max(1, split - probe.length - 2); // head lines, the closing brace, the final newline
  let file = 0;
  for (let lo = 0; lo < total || file === 0; lo += perFile, file++) {
    const hi = Math.min(total, lo + perFile);
    const L = head(file, lo, hi);
    for (let i = lo; i < hi; i++) L.push(line(i));
    L.push('}');
    const nm = prefix + '-' + pad3(file) + '.mjs';
    write(nm, L);
    names.push(nm);
    if (hi >= total) break;
  }
  return names;
}

const J = (v) => JSON.stringify(v);
const pad3 = (n) => String(n).padStart(3, '0');
const toPosix = (p) => p.replaceAll('\\', '/');
const ident = (file) => file.replace(/\.mjs$/, '').replace(/[^A-Za-z0-9]/g, '_');

// ---------------------------------------------------------------- prune (MANUAL P8)
//
// A census (tools/organism-census.mjs) loads an emitted organism, drives it, and records
// which declared cells ran at least once and which declared edges delivered at least once.
// It writes that liveness as two bitsets, one bit per cell and one bit per edge, in load
// order. Load order is line order: loadOrganism replays the c() lines and e() lines in the
// order the files list them, Wiring.add appends each accepted edge at the next index, and an
// emitted organism carries no duplicate edge (the census refuses a seed whose reload reports
// one, because then the line to index mapping would be off by the duplicates).
//
// pruneBrain copies a brain keeping every declaration the census saw do something: every
// cell that ran (a cell that fired ran), every edge that delivered, every edge still carrying
// a signal at the end when the census recorded those, both endpoints of every kept edge (a
// cell that never ran but received a delivery is kept, so a delivered edge is never dropped
// for want of an endpoint), every declaration the caller protects (the cells the hosted
// problems ran on, and every declaration of a file whose knockout lowered a hosted score),
// and the regions and circuits that still hold a kept cell. What goes is only what never ran
// and never delivered. The copy is then written by the same emitOrganism above, so the
// pruned seed is loaded by the same loader and checked by the same verify() as any other.

/**
 * Encode liveness as a bitset: bit i set when isLive(i).
 * @param {number} n @param {(i:number)=>boolean} isLive
 * @returns {{ n: number, count: number, encoding: string, b64: string }}
 */
export function liveBits(n, isLive) {
  const bytes = new Uint8Array((n + 7) >> 3);
  let count = 0;
  for (let i = 0; i < n; i++) if (isLive(i)) { bytes[i >> 3] |= 1 << (i & 7); count++; }
  return { n, count, encoding: 'bitset, bit i of byte i>>3 at position i&7, base64', b64: Buffer.from(bytes).toString('base64') };
}

/**
 * Decode a liveBits object and check it: the popcount must equal the recorded count.
 * @param {{ n: number, count: number, b64: string }} o
 * @returns {{ n: number, count: number, has: (i:number)=>boolean }}
 */
export function readLiveBits(o) {
  if (!o || !Number.isInteger(o.n) || typeof o.b64 !== 'string') throw new Error('prune: liveness is not a liveBits object');
  const bytes = Buffer.from(o.b64, 'base64');
  if (bytes.length !== ((o.n + 7) >> 3)) throw new Error('prune: liveness holds ' + bytes.length + ' bytes for ' + o.n + ' bits');
  let count = 0;
  for (let i = 0; i < o.n; i++) if ((bytes[i >> 3] >> (i & 7)) & 1) count++;
  if (count !== o.count) throw new Error('prune: liveness popcount ' + count + ' does not match its recorded count ' + o.count);
  return { n: o.n, count, has: (i) => ((bytes[i >> 3] >> (i & 7)) & 1) === 1 };
}

/**
 * Copy a brain keeping only what a census found alive.
 * @param {object} brain a freshly loaded organism (never ticked: params are copied as they are)
 * @param {{ cells: {n, has}, edges: {n, has}, inFlight?: {n, has} }} live readers from readLiveBits
 * @param {object} [opts] { name, note, protect: { cells: Iterable<idx>, edges: Iterable<idx>, why } }
 * @returns {{ brain: object, dropped: object, kept: object }}
 */
export function pruneBrain(brain, live, { name = null, note = null, protect = null } = {}) {
  const k = brain.connectome;
  if (!live || !live.cells || !live.edges) throw new Error('prune: need { cells, edges } liveness');
  if (live.cells.n !== brain.cells.length) throw new Error('prune: liveness covers ' + live.cells.n + ' cells, the brain has ' + brain.cells.length);
  if (live.edges.n !== k.n) throw new Error('prune: liveness covers ' + live.edges.n + ' edges, the brain has ' + k.n);
  if (live.inFlight && live.inFlight.n !== k.n) throw new Error('prune: in flight liveness covers ' + live.inFlight.n + ' edges, the brain has ' + k.n);
  const { loaded, hash, wiring, pruned: priorPrune, ...genome } = brain.genome || {};
  const runtime = genome.runtime || {};
  const outName = name || brain.name + '-pruned';
  const out = new Brain({
    name: outName, seed: genome.seed ?? brain.name,
    ledger: 'off', pruneEvery: 0, ...runtime,
    policy: monomorphicGrowth(runtime.gate || {}),
  });

  // what is kept: ran, delivered, in flight, protected, and the endpoints of every kept edge
  const nC = brain.cells.length;
  const keepCell = new Uint8Array(nC), keepEdge = new Uint8Array(k.n);
  const protCells = new Uint8Array(nC), protEdges = new Uint8Array(k.n);
  for (const i of (protect && protect.cells) || []) { if (!(i >= 0 && i < nC)) throw new Error('prune: protected cell ' + i + ' is out of range'); protCells[i] = 1; }
  for (const e of (protect && protect.edges) || []) { if (!(e >= 0 && e < k.n)) throw new Error('prune: protected edge ' + e + ' is out of range'); protEdges[e] = 1; }
  let cellsRan = 0, cellsProtectedOnly = 0, cellsEndpointOnly = 0, edgesDelivered = 0, edgesInFlightOnly = 0, edgesProtectedOnly = 0;
  for (let i = 0; i < nC; i++) {
    if (live.cells.has(i)) { keepCell[i] = 1; cellsRan++; }
    else if (protCells[i]) { keepCell[i] = 1; cellsProtectedOnly++; }
  }
  for (let e = 0; e < k.n; e++) {
    if (live.edges.has(e)) { keepEdge[e] = 1; edgesDelivered++; }
    else if (live.inFlight && live.inFlight.has(e)) { keepEdge[e] = 1; edgesInFlightOnly++; }
    else if (protEdges[e]) { keepEdge[e] = 1; edgesProtectedOnly++; }
    else continue;
    for (const i of [k.src[e], k.dst[e]]) if (!keepCell[i]) { keepCell[i] = 1; cellsEndpointOnly++; }
  }
  const liveRegions = new Set(), liveCircuits = new Set();
  for (let i = 0; i < nC; i++) {
    if (!keepCell[i]) continue;
    const c = brain.cells[i];
    liveRegions.add(c.region); liveCircuits.add(c.region + '/' + c.circuit);
  }
  let regionsDropped = 0, circuitsDropped = 0;
  for (const rg of brain.regions.values()) {
    if (liveRegions.has(rg.name)) out.addRegion(rg.name, { budget: rg.budget, doc: rg.doc || '' }); else regionsDropped++;
  }
  for (const c of brain.circuits.values()) {
    if (liveCircuits.has(c.region + '/' + c.name)) out.addCircuit(c.region, c.name, { period: c.period, doc: c.doc || '' }); else circuitsDropped++;
  }
  const newIdx = new Int32Array(brain.cells.length).fill(-1);
  for (let i = 0; i < brain.cells.length; i++) {
    if (!keepCell[i]) continue;
    const c = brain.cells[i];
    newIdx[i] = out.addCell({ id: c.id, kind: c.kind, region: c.region, circuit: c.circuit, params: JSON.parse(JSON.stringify(c.params)), policy: JSON.parse(JSON.stringify(c.policy)) }).idx;
  }
  const wiringOut = new Wiring(out, { reserve: edgesDelivered + edgesInFlightOnly + edgesProtectedOnly, strict: true });
  let edgesDead = 0, orphaned = 0;
  for (let e = 0; e < k.n; e++) {
    if (!keepEdge[e]) { edgesDead++; continue; }
    const a = newIdx[k.src[e]], z = newIdx[k.dst[e]];
    if (a < 0 || z < 0) { orphaned++; continue; }
    wiringOut.add(a, z, k.srcPort[e], k.dstPort[e], { w: k.w[e], delay: k.delay[e], conf: k.conf[e] });
  }
  wiringOut.finish();
  // a kept edge always keeps both endpoints, so nothing can be orphaned; say so if it ever is
  if (orphaned) throw new Error('prune: ' + orphaned + ' kept edges lost an endpoint');
  const dropped = {
    cells: nC - out.cells.length, edgesNeverDelivered: edgesDead, edgesOrphaned: 0,
    edges: k.n - out.connectome.n, regions: regionsDropped, circuits: circuitsDropped,
  };
  const kept = {
    cells: { ran: cellsRan, protectedOnly: cellsProtectedOnly, endpointOnly: cellsEndpointOnly },
    edges: { delivered: edgesDelivered, inFlightOnly: edgesInFlightOnly, protectedOnly: edgesProtectedOnly, inFlightRecorded: !!live.inFlight },
    protect: { cells: protCells.reduce((a, b) => a + b, 0), edges: protEdges.reduce((a, b) => a + b, 0), why: (protect && protect.why) || [] },
  };
  out.genome = {
    ...genome, name: outName,
    pruned: {
      from: brain.name, fromHash: hash ?? null,
      cells: { before: nC, after: out.cells.length },
      edges: { before: k.n, after: out.connectome.n, neverDelivered: edgesDead, orphaned: 0 },
      kept,
      regionsDropped, circuitsDropped, wiring: { added: wiringOut.added, duplicates: wiringOut.duplicates, illegal: wiringOut.illegal },
      ...(note ? { census: note } : {}),
    },
  };
  return { brain: out, dropped, kept };
}

/**
 * The declarations of each emitted file, as index ranges in load order: cells files in the
 * order the manifest lists them give cells 0, 1, ...; edges files likewise give edges. This is
 * the same line order loadOrganism replays.
 * @param {string} dir @param {object} manifest
 * @returns {Map<string, { kind: 'cells'|'edges', start: number, count: number }>}
 */
export function declarationRanges(dir, manifest) {
  const out = new Map();
  let nc = 0, ne = 0;
  for (const f of manifest.files || []) {
    const kind = /^cells-/.test(f.path) ? 'cells' : /^edges-/.test(f.path) ? 'edges' : null;
    if (!kind) continue;
    const pre = kind === 'cells' ? 'c(' : 'e(';
    let count = 0;
    for (const line of readFileSync(path.join(dir, f.path), 'utf8').split('\n')) if (line.startsWith(pre)) count++;
    out.set(f.path, { kind, start: kind === 'cells' ? nc : ne, count });
    if (kind === 'cells') nc += count; else ne += count;
  }
  return out;
}

/**
 * What a census verdict protects from pruning beyond its liveness: the cells its hosted
 * problems ran on, and every declaration of a file whose knockout lowered a hosted score.
 * @param {object} census a census verdict
 * @param {object} brain the loaded seed @param {string} dir @param {object} manifest
 * @returns {{ cells: number[], edges: number[], why: string[] }}
 */
export function protectedByCensus(census, brain, dir, manifest) {
  const cells = new Set(), edges = new Set(), why = [];
  const idxOf = new Map(brain.cells.map((c, i) => [c.id, i]));
  const hosted = [];
  for (const suite of ['algebra', 'sequence']) for (const id of (census.tasks && census.tasks[suite] && census.tasks[suite].cells) || []) hosted.push(id);
  for (const id of hosted) { const i = idxOf.get(id); if (i === undefined) throw new Error('prune: the census hosted a problem on ' + id + ', which the seed does not declare'); cells.add(i); }
  if (hosted.length) why.push(hosted.length + ' cells the hosted problems ran on (' + hosted.join(', ') + ')');
  let ranges = null;
  for (const ko of census.knockouts || []) {
    const d = ko.delta || {};
    const lowered = (d.taskScore || 0) < 0 || (d.algebraCorrect || 0) < 0 || (d.sequenceCorrect || 0) < 0;
    if (!lowered) { why.push('knockout of ' + ko.file + ' (' + ko.role + ') lowered no hosted score (task score delta ' + (d.taskScore || 0) + '), so it protects nothing beyond what ran or delivered'); continue; }
    ranges = ranges || declarationRanges(dir, manifest);
    const r = ranges.get(ko.file);
    if (!r) throw new Error('prune: knockout file ' + ko.file + ' is not in the manifest');
    for (let j = r.start; j < r.start + r.count; j++) (r.kind === 'cells' ? cells : edges).add(j);
    why.push('knockout of ' + ko.file + ' (' + ko.role + ') lowered a hosted score (task score delta ' + d.taskScore + '), so all ' + r.count + ' of its ' + r.kind + ' are kept');
  }
  return { cells: [...cells], edges: [...edges], why };
}

// ---------------------------------------------------------------- CLI
//   node genome/emit.mjs --prune bench/verdicts/census.json [--seed organism/gen-0]
//                        [--out dir] [--name gen-0-pruned]
// Loads the seed the census was taken on (refusing one whose manifest hash differs), writes
// the pruned copy (default bench/verdicts/.census/<name>, a dot directory the gate does not
// count as generated lines), then loads the pruned copy back and verifies it.
export async function pruneMain(argv) {
  const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
  const censusFile = path.resolve(opt('prune', ''));
  if (!existsSync(censusFile)) throw new Error('prune: no census file at ' + censusFile);
  const census = JSON.parse(readFileSync(censusFile, 'utf8'));
  if (!census.live || !census.live.cells || !census.live.edges) throw new Error('prune: ' + censusFile + ' carries no liveness (a census written by tools/organism-census.mjs does)');
  const seedDir = path.resolve(BRAIN_ROOT, opt('seed', census.seed));
  const name = opt('name', path.basename(seedDir) + '-pruned');
  const outDir = path.resolve(opt('out', path.join(BRAIN_ROOT, 'bench', 'verdicts', '.census', name)));
  const say = argv.includes('--quiet') ? () => {} : (s) => process.stdout.write(s + '\n');
  await import('../cells/all.mjs');
  const { loadFrom, verify } = await import('./load.mjs');
  const t0 = Date.now();
  const { brain, manifest } = await loadFrom(seedDir);
  if (census.live.manifestHash !== manifest.hash) throw new Error('prune: the census was taken on organism hash ' + census.live.manifestHash + ', ' + seedDir + ' has ' + manifest.hash);
  const cells = readLiveBits(census.live.cells), edges = readLiveBits(census.live.edges);
  const inFlight = census.live.inFlight ? readLiveBits(census.live.inFlight) : null;
  const protect = protectedByCensus(census, brain, seedDir, manifest);
  const { brain: pruned, dropped, kept } = pruneBrain(brain, { cells, edges, inFlight }, { name, protect, note: { file: toPosix(path.relative(BRAIN_ROOT, censusFile)), at: census.at, ticks: census.ticks, phases: census.live.phases } });
  const res = emitOrganism(pruned, { dir: outDir });
  const back = await loadFrom(outDir);
  const v = verify(back.brain, back.manifest);
  const wantCells = pruned.cells.length, wantEdges = pruned.connectome.n;
  // the invariant, checked on the reloaded copy: every cell that ran and every edge that
  // delivered is still declared, by id and by its two endpoints and ports
  const backIdx = new Map(back.brain.cells.map((c, i) => [c.id, i]));
  let lostCells = 0, lostEdges = 0;
  for (let i = 0; i < brain.cells.length; i++) if (cells.has(i) && !backIdx.has(brain.cells[i].id)) lostCells++;
  const bk = back.brain.connectome, sk = brain.connectome, have = new Set();
  for (let e = 0; e < bk.n; e++) have.add(back.brain.cells[bk.src[e]].id + '>' + back.brain.cells[bk.dst[e]].id + ':' + bk.srcPort[e] + ':' + bk.dstPort[e]);
  for (let e = 0; e < sk.n; e++) if ((edges.has(e) || (inFlight && inFlight.has(e))) && !have.has(brain.cells[sk.src[e]].id + '>' + brain.cells[sk.dst[e]].id + ':' + sk.srcPort[e] + ':' + sk.dstPort[e])) lostEdges++;
  const linesBefore = manifest.counts && manifest.counts.lines;
  const ok = v.ok && back.brain.cells.length === wantCells && bk.n === wantEdges && lostCells === 0 && lostEdges === 0;
  say('prune ' + toPosix(path.relative(BRAIN_ROOT, seedDir)) + ' by ' + toPosix(path.relative(BRAIN_ROOT, censusFile)) + ' (census at ' + census.at + ', ' + census.ticks + ' ticks)');
  say('  lines ' + linesBefore + ' -> ' + res.lines + ' (manifest count, the gate way): ' + (linesBefore - res.lines) + ' lines removed, ' + (100 * (linesBefore - res.lines) / linesBefore).toFixed(2) + '% of the seed');
  say('  cells ' + brain.cells.length + ' -> ' + pruned.cells.length + ': kept ' + kept.cells.ran + ' that ran, ' + kept.cells.protectedOnly + ' protected that never ran, ' + kept.cells.endpointOnly + ' that never ran but are an endpoint of a kept edge; dropped ' + dropped.cells);
  say('  edges ' + brain.connectome.n + ' -> ' + pruned.connectome.n + ': kept ' + kept.edges.delivered + ' that delivered, ' + kept.edges.inFlightOnly + ' in flight at the end' + (kept.edges.inFlightRecorded ? '' : ' (this census recorded no in flight set)') + ', ' + kept.edges.protectedOnly + ' protected; dropped ' + dropped.edgesNeverDelivered + ' that never delivered');
  for (const w of protect.why) say('  protect    ' + w);
  say('  regions dropped ' + dropped.regions + ', circuits dropped ' + dropped.circuits);
  say('  emitted ' + toPosix(path.relative(BRAIN_ROOT, res.dir)) + ': ' + (res.files.length + 1) + ' files, ' + res.lines + ' lines (manifest count, the gate way), ' + res.bytes + ' bytes before the manifest');
  say('  round trip: loaded ' + back.brain.cells.length + ' cells and ' + bk.n + ' edges (expected ' + wantCells + ' and ' + wantEdges + '), verify ' + (v.ok ? 'ok' : 'FAILED: ' + v.errors.join('; ')) + ', hash ' + v.hash.slice(0, 16) + '; of what ran or delivered, ' + lostCells + ' cells and ' + lostEdges + ' edges are missing from the copy');
  say('  ' + (ok ? 'ROUND TRIP OK' : 'ROUND TRIP FAILED') + ' in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  return { ok, dir: res.dir, dropped, kept, protect, lines: { before: linesBefore, after: res.lines }, cells: back.brain.cells.length, edges: bk.n, expected: { cells: wantCells, edges: wantEdges }, lost: { cells: lostCells, edges: lostEdges }, verify: v };
}

